function run_step04CC2_fixed_T_dataset_h2(workDir,datasetId)
%RUN_STEP04CC2_FIXED_T_DATASET_H2 Evaluate three frozen C1 decisions only.

started=tic;workDir=string(workDir);datasetId=double(datasetId);
thisDir=fileparts(mfilename('fullpath'));rootDir=fileparts(fileparts(thisDir));
addpath(rootDir);addpath(thisDir);add_gurobi_path();
assert_git_gate("task/002-stage2b-b3-smoke", ...
    "dbdb728961c623e976cb1a749310ebbeb5f32810");
if ~isscalar(datasetId)||datasetId<1||datasetId>3||datasetId~=floor(datasetId)
    error('datasetId must be 1, 2, or 3.');
end
datasetDir=fullfile(workDir,sprintf('dataset-%03d',datasetId));
if isfolder(datasetDir)
    entries=dir(datasetDir);entries=entries(~ismember({entries.name},{'.','..'}));
    if ~isempty(entries)
        error('Refusing to overwrite nonempty dataset directory.');
    end
else
    mkdir(datasetDir);
end
diary(fullfile(datasetDir,'matlab_diary.txt'));cleanupDiary=onCleanup(@()diary('off'));

c1File=fullfile(rootDir,'results','task-002-stage2b-b3-smoke', ...
    '46-flat-chi2-eta-calibration','run-003','eta_full_results.csv');
if sha256_file(c1File)~="16947d17fc2a3ff4a30bb966e14b5b76a0bf19a27dec48722ab405b930c6daf0"
    error('C1 decision table hash gate failed.');
end
decisions=read_frozen_decisions(c1File);
matFile=fullfile(workDir,sprintf('independent_dataset_%03d.mat',datasetId));
if ~isfile(matFile),error('Independent dataset MAT is missing.');end
manifest=readtable(fullfile(workDir,'independent_dataset_manifest.csv'));
mrow=manifest(double(manifest.dataset_id)==datasetId,:);
if height(mrow)~=1||string(mrow.local_mat_sha256)~=sha256_file(matFile)|| ...
        double(mrow.sample_count)~=15000||abs(double(mrow.weight_sum)-1)>1e-14
    error('Independent dataset manifest/hash/weight gate failed.');
end
S=load(matFile,'identity','Dperiod','Aperiod','Cperiod');R=size(S.Dperiod,1);
if R~=15000||height(S.identity)~=R||any(double(S.identity.dataset_id)~=datasetId)|| ...
        any(double(S.identity.a0)~=4)||any(double(S.identity.loc0)~=5)|| ...
        any(double(S.identity.lfw0)~=0)||max(abs(double(S.identity.sample_weight)-1/R))>0
    error('Independent state19 dataset identity gate failed.');
end

config=struct('gurobiOutputFlag',0,'gurobiFeasibilityTol',1e-9, ...
    'gurobiOptimalityTol',1e-9,'gurobiThreads',1,'objectiveScale',1e5, ...
    'gurobiTimeLimit',1800);
gamma=2; Cap=[300,200,100,150];
scenarioTables=cell(3,1);summaryRows=cell(3,37);certificateRows=cell(3,15);
for jj=1:3
    T=double([decisions.T1_kg(jj),decisions.T2_kg(jj), ...
        decisions.T3_kg(jj),decisions.T4_kg(jj)]);
    fprintf('STEP04CC2_FIXED_T_START|dataset=%d|decision=%s|eta=%.12g\n', ...
        datasetId,string(decisions.decision_label(jj)),decisions.eta(jj));
    ev=evaluate_step04CA2_period_fixed_T_detailed_h2(S.Dperiod,S.Aperiod,S.Cperiod, ...
        repmat(T,R,1),2000,config);
    if ev.exitflag~=1||ev.status~="OPTIMAL",error('Fixed-T evaluation failed: %s',ev.status);end
    residual=max([ev.max_demand_balance_error,max(0,ev.max_site_capacity_violation), ...
        ev.objective_reconstruction_abs_error/max(1,sum(abs(ev.operating_loss)))],[],'omitnan');
    if residual>1e-7,error('Fixed-T mechanical residual failed: %.15g',residual);end
    firstStage=gamma*sum(T);totalCost=firstStage+ev.operating_loss;
    serviceRate=max(0,min(1,ev.service_satisfaction_rate));
    binding=abs(T-Cap)<=1e-6;
    summaryRows(jj,:)={datasetId,jj,string(decisions.decision_label(jj)), ...
        decisions.eta(jj),T(1),T(2),T(3),T(4),sum(T),binding(1),binding(2), ...
        binding(3),binding(4),sum(binding),R,1/R,sum(repmat(1/R,R,1)), ...
        mean(totalCost),mean(ev.operating_loss),mean(ev.service_cost), ...
        mean(ev.shortage_kg),mean(serviceRate),sum(ev.shortage_kg<=1e-9)/R, ...
        pct(ev.operating_loss,.95),pct(ev.operating_loss,.99),pct(ev.operating_loss,.995), ...
        tail_mean(ev.operating_loss,.95),tail_mean(ev.operating_loss,.99), ...
        tail_mean(ev.operating_loss,.995),max(ev.operating_loss), ...
        pct(ev.shortage_kg,.95),pct(ev.shortage_kg,.99),pct(ev.shortage_kg,.995), ...
        max(ev.shortage_kg),ev.solve_runtime_sec,residual,string(ev.status)};
    certificatePass=ev.exitflag==1&&ev.status=="OPTIMAL"&&residual<=1e-7&& ...
        abs(sum(repmat(1/R,R,1))-1)<=1e-12;
    certificateRows(jj,:)={datasetId,jj,string(decisions.decision_label(jj)), ...
        decisions.eta(jj),string(ev.status),ev.exitflag,R,1/R,1, ...
        ev.max_demand_balance_error,ev.max_site_capacity_violation, ...
        ev.objective_reconstruction_abs_error,residual,ev.solve_runtime_sec,certificatePass};
    scenarioId=double(S.identity.scenario_id);sampleWeight=double(S.identity.sample_weight);
    scenarioTables{jj}=table(repmat(datasetId,R,1),scenarioId,repmat(jj,R,1), ...
        repmat(string(decisions.decision_label(jj)),R,1),repmat(decisions.eta(jj),R,1), ...
        repmat(T(1),R,1),repmat(T(2),R,1),repmat(T(3),R,1),repmat(T(4),R,1), ...
        repmat(sum(T),R,1),sampleWeight,repmat(firstStage,R,1),totalCost, ...
        ev.operating_loss,ev.service_cost,ev.shortage_kg,serviceRate,ev.total_demand_kg, ...
        'VariableNames',{'dataset_id','scenario_id','decision_id','decision_label', ...
        'eta','T1_kg','T2_kg','T3_kg','T4_kg','TerminalLOH_total_kg', ...
        'sample_weight','first_stage_cost','total_cost','operating_loss', ...
        'service_cost','shortage_kg','service_rate','total_demand_kg'});
    fprintf('STEP04CC2_FIXED_T_COMPLETE|dataset=%d|decision=%s|runtime=%.3f\n', ...
        datasetId,string(decisions.decision_label(jj)),ev.solve_runtime_sec);
end

summary=cell2table(summaryRows,'VariableNames',{'dataset_id','decision_id', ...
    'decision_label','eta','T1_kg','T2_kg','T3_kg','T4_kg','TerminalLOH_total_kg', ...
    'T1_capacity_binding','T2_capacity_binding','T3_capacity_binding', ...
    'T4_capacity_binding','capacity_binding_count','sample_count','sample_weight', ...
    'weight_sum','mean_total_cost','mean_operating_loss','mean_service_cost', ...
    'mean_shortage_kg','mean_service_rate','zero_shortage_service_share', ...
    'operating_loss_q95','operating_loss_q99','operating_loss_q995', ...
    'operating_loss_CVaR95','operating_loss_CVaR99','operating_loss_CVaR995', ...
    'maximum_operating_loss','shortage_q95_kg','shortage_q99_kg','shortage_q995_kg', ...
    'maximum_shortage_kg','fixed_T_solve_runtime_sec','maximum_mechanical_residual', ...
    'solver_status'});
certificate=cell2table(certificateRows,'VariableNames',{'dataset_id','decision_id', ...
    'decision_label','eta','solver_status','exitflag','sample_count','sample_weight', ...
    'weight_sum','max_demand_balance_error','max_site_capacity_violation', ...
    'objective_reconstruction_abs_error','maximum_mechanical_residual', ...
    'solve_runtime_sec','certificate_pass'});
scenarioResults=vertcat(scenarioTables{:});
writetable(summary,fullfile(datasetDir,'fixed_T_summary.csv'));
writetable(certificate,fullfile(datasetDir,'fixed_T_certificate.csv'));
writetable(scenarioResults,fullfile(datasetDir,'scenario_results.csv'));
if any(~certificate.certificate_pass)||height(scenarioResults)~=45000
    error('Dataset fixed-T output/certificate gate failed.');
end
fid=fopen(fullfile(datasetDir,'mechanical_audit.txt'),'w');cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'status=PASS\ndataset_id=%d\nscenario_count=15000\ndecision_count=3\n',datasetId);
fprintf(fid,'TerminalLOH_optimization_calls=0\nchi2_worst_probability_calls=0\nCVaR_objective_calls=0\n');
fprintf(fid,'maximum_mechanical_residual=%.15g\nweight_sum=1\n',max(certificate.maximum_mechanical_residual));
fprintf(fid,'fixed_T_source=C1_run-003_nominal_optimization\n');
fprintf('STEP04CC2_DATASET_PROCESS_COMPLETE|dataset=%d|runtime=%.3f\n',datasetId,toc(started));
end

function decisions=read_frozen_decisions(c1File)
t=readtable(c1File);etaWanted=[0;0.003;0.01];labels=["SAA";"ETA_0.003";"ETA_0.01"];
rows=zeros(3,1);for ii=1:3,hit=find(abs(double(t.eta)-etaWanted(ii))<=1e-14);if numel(hit)~=1,error('C1 eta row missing.');end;rows(ii)=hit;end
s=t(rows,:);T=[s.T1_kg,s.T2_kg,s.T3_kg,s.T4_kg];expected=[294.589913536808,138.832065024684,93.0093009300931,150;299.211738691929,137.483280118695,94.3580963878466,150;300,143.468150246686,100,150];
if max(abs(T-expected),[],'all')>1e-10||any(string(s.solver_status)~="OPTIMAL")||any(string(s.audit_status)~="PASS"),error('C1 decision audit failed.');end
decisions=table((1:3).',labels,etaWanted,T(:,1),T(:,2),T(:,3),T(:,4));
decisions.Properties.VariableNames={'decision_id','decision_label','eta','T1_kg','T2_kg','T3_kg','T4_kg'};
end
function value=pct(x,p),x=sort(double(x(:)));x=x(isfinite(x));value=x(max(1,min(numel(x),ceil(p*numel(x)))));end
function value=tail_mean(x,p),x=double(x(:));threshold=pct(x,p);value=mean(x(x>=threshold));end
function hash=sha256_file(fileName)
fid=fopen(fileName,'rb');if fid<0,error('Could not open %s.',fileName);end;cleanup=onCleanup(@()fclose(fid));
md=java.security.MessageDigest.getInstance('SHA-256');while true,bytes=fread(fid,1024*1024,'*uint8');if isempty(bytes),break;end;md.update(typecast(bytes,'int8'));end
digest=typecast(md.digest(),'uint8');hash=lower(string(reshape(dec2hex(digest,2).',1,[])));
end
function assert_git_gate(expectedBranch,expectedHead)
[s1,b]=system('git branch --show-current');[s2,h]=system('git rev-parse HEAD');[s3,u]=system('git rev-parse @{upstream}');
if s1~=0||s2~=0||s3~=0||strtrim(string(b))~=expectedBranch||strtrim(string(h))~=expectedHead||strtrim(string(u))~=expectedHead,error('Step-04C-C2 dataset Git gate failed.');end
end
function add_gurobi_path()
for candidate={fullfile(getenv('GUROBI_HOME'),'matlab'),'D:\gurobi1201\win64\matlab','C:\gurobi1201\win64\matlab'}
    if ~isempty(candidate{1})&&isfolder(candidate{1}),addpath(candidate{1});end
end
end
