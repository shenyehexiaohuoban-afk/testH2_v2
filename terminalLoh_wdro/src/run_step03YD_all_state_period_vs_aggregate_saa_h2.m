function digest=path_digest(path)
if isfile(path),digest=sha256_file(path);return;end
if ~isfolder(path),digest="MISSING";return;end
files=dir(fullfile(path,'**','*'));files=files(~[files.isdir]);relative=strings(numel(files),1);
for ii=1:numel(files),fullName=fullfile(files(ii).folder,files(ii).name);relative(ii)=string(erase(fullName,[char(path),filesep]));end
[relative,order]=sort(relative);files=files(order);md=java.security.MessageDigest.getInstance('SHA-256');
for ii=1:numel(files),fullName=fullfile(files(ii).folder,files(ii).name);token=relative(ii)+"|"+string(files(ii).bytes)+"|"+sha256_file(fullName)+newline;md.update(typecast(unicode2native(char(token),'UTF-8'),'int8'));end
raw=typecast(md.digest(),'uint8');digest=lower(string(reshape(dec2hex(raw,2).',1,[])));
end

function hash=sha256_file(fileName)
fid=fopen(fileName,'rb');if fid<0,error('Cannot open protected file.');end;cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,bytes=fread(fid,1024*1024,'*uint8');if isempty(bytes),break;end;md.update(typecast(bytes,'int8'));end
raw=typecast(md.digest(),'uint8');hash=lower(string(reshape(dec2hex(raw,2).',1,[])));clear cleanup;
end

function write_lines(fileName,lines)
