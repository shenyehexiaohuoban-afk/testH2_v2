function screening = build_screening(cases, stateIds, Cap, closeCap, closeRegret, ~)
rows = cell(numel(stateIds), 29);
for ss = 1:numel(stateIds)
    c100 = cases{ss,1}; c500 = cases{ss,2}; complete = c100.pass && c500.pass;
    if complete
        maxSiteDiff = max(abs(c500.period.T-c500.aggregate.T));
        maxSiteFraction = max(abs(c500.period.T-c500.aggregate.T)./Cap);
        totalDiff = abs(sum(c500.period.T)-sum(c500.aggregate.T));
        aggregateSat = sum(c500.aggregate.T_at_upper_bound);
        periodSat = sum(c500.period.T_at_upper_bound);
        maxRegret = max(c500.aggregate_relative_regret,c500.period_relative_regret);
        close = maxSiteFraction <= closeCap && totalDiff/sum(Cap) <= closeCap && maxRegret <= closeRegret;
        stableAgg = max(abs(c500.aggregate.T-c100.aggregate.T)./Cap);
        stablePeriod = max(abs(c500.period.T-c100.period.T)./Cap);
        aggregateRel = c500.aggregate_relative_regret;
        periodRel = c500.period_relative_regret;
        aggregateTotal = sum(c500.aggregate.T);
        periodTotal = sum(c500.period.T);
        aggregateObjective = c500.aggregate.objective_value;
        periodObjective = c500.period.objective_value;
        aggregateShortage = c500.aggregate.mean_shortage_loss;
        periodShortage = c500.period.mean_shortage_loss;
        message = "";
    else
        maxSiteDiff=NaN;maxSiteFraction=NaN;totalDiff=NaN;aggregateSat=NaN;periodSat=NaN;maxRegret=NaN;
        close=false;stableAgg=NaN;stablePeriod=NaN;
        aggregateRel=NaN;periodRel=NaN;aggregateTotal=NaN;periodTotal=NaN;
        aggregateObjective=NaN;periodObjective=NaN;aggregateShortage=NaN;periodShortage=NaN;
        message=strjoin(unique([c100.failure_message;c500.failure_message])," | ");
    end
    rows(ss,:)={stateIds(ss),complete,c100.positive_demand_count,c500.positive_demand_count, ...
        c100.mean_total_demand,c500.mean_total_demand,c100.max_total_demand,c500.max_total_demand, ...
        maxSiteDiff,maxSiteFraction,totalDiff,aggregateSat,periodSat, ...
        aggregateRel,periodRel,maxRegret,close, ...
        stableAgg,stablePeriod,aggregateTotal,periodTotal, ...
        aggregateObjective,periodObjective,aggregateShortage,periodShortage, ...
        false,false,false,message};
end
screening=cell2table(rows,'VariableNames',{'initial_state_id','state_complete', ...
    'positive_demand_count_R100','positive_demand_count_R500','mean_demand_R100_kg', ...
    'mean_demand_R500_kg','max_demand_R100_kg','max_demand_R500_kg', ...
    'max_site_T_difference_R500_kg','max_site_T_difference_fraction_R500', ...
    'total_T_difference_R500_kg','aggregate_capacity_hits_R500', ...
    'period_capacity_hits_R500','aggregate_relative_regret_R500', ...
    'period_relative_regret_R500','max_relative_regret_R500','close_diagnostic_R500', ...
    'aggregate_max_R100_R500_site_fraction','period_max_R100_R500_site_fraction', ...
    'aggregate_total_T_R500','period_total_T_R500','aggregate_objective_R500', ...
    'period_objective_R500','aggregate_shortage_loss_R500','period_shortage_loss_R500', ...
    'recommended_attention_state','recommended_control_state','recommendation_eligible', ...
    'failure_message'});
end

function [screening, lines] = select_recommended_states(screening, tol)
complete = screening.state_complete;
eligible = complete & screening.positive_demand_count_R500 > 0 & ...
    screening.aggregate_capacity_hits_R500 < 4 & screening.period_capacity_hits_R500 < 4;
screening.recommendation_eligible = eligible;
positiveThreshold = qvalue(screening.positive_demand_count_R500(complete),0.75);
if any(eligible)
    differenceThreshold = qvalue(screening.max_site_T_difference_R500_kg(eligible),0.75);
else
    differenceThreshold = Inf;
end
attention = eligible & screening.positive_demand_count_R500 >= positiveThreshold & ...
    screening.max_site_T_difference_R500_kg >= differenceThreshold & ...
    screening.max_site_T_difference_R500_kg > tol;
screening.recommended_attention_state = attention;
control = false(height(screening),1);
if any(eligible)
    candidates=find(eligible);
    score=screening.max_site_T_difference_fraction_R500(candidates)+ ...
        screening.max_relative_regret_R500(candidates);
    [~,order]=sortrows([score,-screening.positive_demand_count_R500(candidates)],[1,2]);
    control(candidates(order(1)))=true;
end
screening.recommended_control_state=control;
attentionIds=screening.initial_state_id(attention);
controlIds=screening.initial_state_id(control);
lines=["selection_basis=R500 actual results only"; ...
    "attention_positive_demand_q75_threshold="+sprintf('%.10g',positiveThreshold); ...
    "attention_T_difference_q75_among_unsaturated_states_kg="+sprintf('%.10g',differenceThreshold); ...
    "attention_states="+id_list(attentionIds); ...
    "control_state="+id_list(controlIds); ...
    "attention_rule=positive count at or above all-state q75; neither model fully capacity-saturated; T difference at or above eligible-state q75"; ...
    "control_rule=eligible state minimizing capacity-normalized T difference plus maximum cross relative regret; ties favor more positive-demand samples"; ...
    "no_forced_state_count=true"];
end

