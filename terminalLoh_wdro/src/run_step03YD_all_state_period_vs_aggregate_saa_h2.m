function data = build_case_data(entry, rows, stateId, R)
data = struct('state_id', stateId, 'R', R, ...
    'identity', entry.identity(rows, :), ...
    'Dagg', entry.Dagg(rows, :), ...
    'Aagg', entry.Aagg(rows, :, :), ...
    'Cagg', entry.Cagg(rows, :, :), ...
    'Dperiod', entry.Dperiod(rows, :, :), ...
    'Aperiod', entry.Aperiod(rows, :, :, :), ...
    'Cperiod', entry.Cperiod(rows, :, :, :));
totalDemand = sum(data.Dagg, 2);
data.positive_demand_count = sum(totalDemand > 1e-10);
data.mean_total_demand = mean(totalDemand);
data.max_total_demand = max(totalDemand);
end

function output = build_solved_case(data, aggregate, period, Cap, tol, objTol)
output = data;
output.aggregate = aggregate;
output.period = period;
output.aggregate_T_in_period = NaN;
output.period_T_in_aggregate = NaN;
output.aggregate_cross_service_cost = NaN;
output.aggregate_cross_shortage_loss = NaN;
output.period_cross_service_cost = NaN;
output.period_cross_shortage_loss = NaN;
output.period_regret_of_aggregate_T = NaN;
output.aggregate_regret_of_period_T = NaN;
output.period_relative_regret = NaN;
output.aggregate_relative_regret = NaN;
output.cross_complete = false;
output.failure_message = "";
output.pass = aggregate.status == "OPTIMAL" && period.status == "OPTIMAL" && ...
    aggregate.objective_weight_sum == 1 && period.objective_weight_sum == 1 && ...
    aggregate.objective_reconstruction_error <= objTol && ...
    period.objective_reconstruction_error <= objTol && ...
    aggregate.max_demand_balance_error <= tol && ...
    period.max_demand_balance_error <= tol && ...
    aggregate.max_site_capacity_violation <= tol && ...
    period.max_site_capacity_violation <= tol && ...
    all(aggregate.T >= -tol & aggregate.T <= Cap + tol) && ...
    all(period.T >= -tol & period.T <= Cap + tol);
if ~output.pass
    output.failure_message = "SAA solve or mechanical reconstruction failed.";
end
end

