    'Aperiod', [], 'Cperiod', [], 'positive_demand_count', NaN, ...
    'mean_total_demand', NaN, 'max_total_demand', NaN, ...
    'aggregate', struct(), 'period', struct(), ...
    'aggregate_T_in_period', NaN, 'period_T_in_aggregate', NaN, ...
    'aggregate_cross_service_cost', NaN, ...
    'aggregate_cross_shortage_loss', NaN, ...
    'period_cross_service_cost', NaN, ...
    'period_cross_shortage_loss', NaN, ...
    'period_regret_of_aggregate_T', NaN, ...
    'aggregate_regret_of_period_T', NaN, ...
    'period_relative_regret', NaN, 'aggregate_relative_regret', NaN, ...
    'cross_complete', false, 'pass', false, ...
    'failure_message', string(message));
end

function [caseRow, solverCalls] = run_state_cross_evaluation( ...
        caseRow, context, config, objTol)
successful = find(cellfun(@(x) x.pass, caseRow));
aggD = []; aggA = []; aggC = []; aggT = [];
periodD = []; periodA = []; periodC = []; periodT = [];
segments = zeros(numel(successful), 2);
offset = 0;
for kk = 1:numel(successful)
    index = successful(kk);
    current = caseRow{index};
    R = current.R;
    segments(kk, :) = [offset + 1, offset + R];
    if kk == 1
        aggD = current.Dagg;
        aggA = current.Aagg;
        aggC = current.Cagg;
        aggT = repmat(current.period.T.', R, 1);
        periodD = current.Dperiod;
        periodA = current.Aperiod;
        periodC = current.Cperiod;
        periodT = repmat(current.aggregate.T.', R, 1);
    else
        aggD = cat(1, aggD, current.Dagg);
        aggA = cat(1, aggA, current.Aagg);
        aggC = cat(1, aggC, current.Cagg);
        aggT = cat(1, aggT, repmat(current.period.T.', R, 1));
        periodD = cat(1, periodD, current.Dperiod);
        periodA = cat(1, periodA, current.Aperiod);
        periodC = cat(1, periodC, current.Cperiod);
        periodT = cat(1, periodT, repmat(current.aggregate.T.', R, 1));
    end
    offset = offset + R;
end
aggregateCross = evaluate_step03T_fixed_T_recourse_h2( ...
    aggD, aggA, aggC, aggT, context.M, config);
periodCross = evaluate_step03Y_period_fixed_T_recourse_h2( ...
    periodD, periodA, periodC, periodT, context.M, config);
solverCalls = 2;
if aggregateCross.status ~= "OPTIMAL" || periodCross.status ~= "OPTIMAL"
    error('State cross-evaluation batch was not OPTIMAL.');
end
for kk = 1:numel(successful)
    index = successful(kk);
    current = caseRow{index};
    rows = segments(kk, 1):segments(kk, 2);
    current.period_T_in_aggregate = context.gamma * sum(current.period.T) + ...
        mean(aggregateCross.operating_loss(rows));
    current.aggregate_T_in_period = context.gamma * sum(current.aggregate.T) + ...
        mean(periodCross.operating_loss(rows));
    current.aggregate_cross_service_cost = mean(aggregateCross.service_cost(rows));
    current.aggregate_cross_shortage_loss = mean(aggregateCross.shortage_loss(rows));
    current.period_cross_service_cost = mean(periodCross.service_cost(rows));
    current.period_cross_shortage_loss = mean(periodCross.shortage_loss(rows));
    current.aggregate_regret_of_period_T = ...
        current.period_T_in_aggregate - current.aggregate.objective_value;
    current.period_regret_of_aggregate_T = ...
        current.aggregate_T_in_period - current.period.objective_value;
    current.aggregate_relative_regret = current.aggregate_regret_of_period_T / ...
        max(1, abs(current.aggregate.objective_value));
    current.period_relative_regret = current.period_regret_of_aggregate_T / ...
        max(1, abs(current.period.objective_value));
    current.cross_complete = current.aggregate_regret_of_period_T >= -objTol && ...
        current.period_regret_of_aggregate_T >= -objTol;
    current.pass = current.pass && current.cross_complete;
    if ~current.cross_complete
        current.failure_message = "Cross objective regret is numerically invalid.";
    end
    caseRow{index} = current;
end
end

function [comparison, cross, stability, screening] = build_output_tables( ...
        cases, stateIds, sampleSizes, Cap, closeCapFraction, closeRegret, tol)
comparisonRows = cell(numel(stateIds) * numel(sampleSizes) * 4, 36);
crossRows = cell(numel(stateIds) * numel(sampleSizes) * 4, 24);
stabilityRows = cell(numel(stateIds) * 2 * 5, 15);
comparisonIndex = 0;
crossIndex = 0;
stabilityIndex = 0;
for ss = 1:numel(stateIds)
    for rr = 1:numel(sampleSizes)
        current = cases{ss, rr};
        if current.pass
            totalAgg = sum(current.aggregate.T);
            totalPeriod = sum(current.period.T);
            totalDiff = abs(totalPeriod - totalAgg);
            for site = 1:4
                comparisonIndex = comparisonIndex + 1;
                comparisonRows(comparisonIndex, :) = {current.state_id, current.R, ...
                    site, current.positive_demand_count, current.mean_total_demand, ...
                    current.max_total_demand, 1/current.R, current.aggregate.T(site), ...
                    current.period.T(site), current.period.T(site)-current.aggregate.T(site), ...
                    abs(current.period.T(site)-current.aggregate.T(site)), ...
                    abs(current.period.T(site)-current.aggregate.T(site))/Cap(site), ...
                    totalAgg, totalPeriod, totalPeriod-totalAgg, totalDiff, ...
                    totalDiff/sum(Cap), current.aggregate.T_at_upper_bound(site), ...
                    current.period.T_at_upper_bound(site), ...
                    current.aggregate.objective_value, current.period.objective_value, ...
                    current.aggregate.holding_cost, current.period.holding_cost, ...
                    current.aggregate.mean_service_cost, current.period.mean_service_cost, ...
                    current.aggregate.mean_shortage_loss, current.period.mean_shortage_loss, ...
                    current.aggregate.mean_operating_loss, current.period.mean_operating_loss, ...
                    current.aggregate_regret_of_period_T, current.period_regret_of_aggregate_T, ...
                    current.aggregate_relative_regret, current.period_relative_regret, ...
                    true, "", current.pass};
            end
            target = ["AGGREGATE"; "PERIOD"; "PERIOD"; "AGGREGATE"];
            source = ["T_AGGREGATE"; "T_PERIOD"; "T_AGGREGATE"; "T_PERIOD"];
            Tmatrix = [current.aggregate.T.'; current.period.T.'; ...
                current.aggregate.T.'; current.period.T.'];
            holding = [current.aggregate.holding_cost; current.period.holding_cost; ...
                current.aggregate.holding_cost; current.period.holding_cost];
            operating = [current.aggregate.mean_operating_loss; ...
                current.period.mean_operating_loss; ...
                current.aggregate_T_in_period-current.aggregate.holding_cost; ...
                current.period_T_in_aggregate-current.period.holding_cost];
            service = [current.aggregate.mean_service_cost; current.period.mean_service_cost; ...
                current.period_cross_service_cost; current.aggregate_cross_service_cost];
            shortage = [current.aggregate.mean_shortage_loss; current.period.mean_shortage_loss; ...
                current.period_cross_shortage_loss; current.aggregate_cross_shortage_loss];
            objective = [current.aggregate.objective_value; current.period.objective_value; ...
                current.aggregate_T_in_period; current.period_T_in_aggregate];
            optimum = [current.aggregate.objective_value; current.period.objective_value; ...
                current.period.objective_value; current.aggregate.objective_value];
            for kk = 1:4
                crossIndex = crossIndex + 1;
                regret = objective(kk)-optimum(kk);
                crossRows(crossIndex, :) = {current.state_id, current.R, ...
                    target(kk), source(kk), Tmatrix(kk,1), Tmatrix(kk,2), ...
                    Tmatrix(kk,3), Tmatrix(kk,4), holding(kk), service(kk), ...
                    shortage(kk), operating(kk), objective(kk), optimum(kk), ...
                    regret, regret/max(1,abs(optimum(kk))), ...
                    current.positive_demand_count, current.mean_total_demand, ...
                    current.max_total_demand, current.aggregate.status, ...
                    current.period.status, true, "", current.pass};
            end
        else
            for site = 1:4
                comparisonIndex = comparisonIndex + 1;
                comparisonRows(comparisonIndex, :) = {current.state_id, current.R, ...
                    site, NaN, NaN, NaN, 1/current.R, NaN, NaN, NaN, NaN, ...
                    NaN, NaN, NaN, NaN, NaN, NaN, false, false, NaN, NaN, ...
                    NaN, NaN, NaN, NaN, NaN, NaN, NaN, NaN, NaN, NaN, ...
                    NaN, NaN, false, current.failure_message, false};
            end
        end
    end
    if cases{ss,1}.pass && cases{ss,2}.pass
        for mode = ["AGGREGATE", "PERIOD"]
            if mode == "AGGREGATE"
                T100 = cases{ss,1}.aggregate.T;
                T500 = cases{ss,2}.aggregate.T;
                z100 = cases{ss,1}.aggregate.objective_value;
                z500 = cases{ss,2}.aggregate.objective_value;
            else
                T100 = cases{ss,1}.period.T;
                T500 = cases{ss,2}.period.T;
                z100 = cases{ss,1}.period.objective_value;
                z500 = cases{ss,2}.period.objective_value;
            end
            for site = 1:5
                stabilityIndex = stabilityIndex + 1;
                if site <= 4
                    a = T100(site); b = T500(site); denominator = Cap(site);
                else
                    a = sum(T100); b = sum(T500); denominator = sum(Cap);
                end
                stabilityRows(stabilityIndex, :) = {stateIds(ss), mode, ...
                    site, a, b, b-a, abs(b-a), abs(b-a)/denominator, ...
                    z100, z500, z500-z100, abs(z500-z100)/max(1,abs(z500)), ...
                    true, "", true};
            end
        end
    end
end
comparisonRows = comparisonRows(1:comparisonIndex,:);
crossRows = crossRows(1:crossIndex,:);
stabilityRows = stabilityRows(1:stabilityIndex,:);
comparison = cell2table(comparisonRows, 'VariableNames', ...
    {'initial_state_id','R','site_id','positive_demand_scenario_count', ...
    'mean_total_demand_kg','max_total_demand_kg','scenario_weight', ...
    'T_aggregate_kg','T_period_kg','period_minus_aggregate_kg', ...
    'site_absolute_difference_kg','site_difference_fraction_of_capacity', ...
    'aggregate_total_T_kg','period_total_T_kg','period_minus_aggregate_total_kg', ...
    'total_absolute_difference_kg','total_difference_fraction_of_total_capacity', ...
    'aggregate_at_capacity','period_at_capacity','aggregate_objective', ...
