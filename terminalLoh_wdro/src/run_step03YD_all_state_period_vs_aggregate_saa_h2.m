function value=qvalue(x,p)
x=sort(double(x(:)));x=x(isfinite(x));if isempty(x),value=NaN;return;end
position=numel(x)*p+0.5;if position<=1,value=x(1);elseif position>=numel(x),value=x(end);else,lo=floor(position);fraction=position-lo;value=x(lo)+fraction*(x(lo+1)-x(lo));end
end

function value=id_list(ids)
ids=double(ids(:));if isempty(ids),value="NONE";else,value=strjoin(string(ids.'),",");end
end

