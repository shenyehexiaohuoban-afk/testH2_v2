function [audit, pass] = audit_probability_semantics(csvPath, matPath)
opts = detectImportOptions(csvPath, 'TextType', 'string');
names = string(opts.VariableNames);
selected = intersect(["initial_state_id", "path_id", "sample_weight", ...
    "dataset_role"], names, 'stable');
opts.SelectedVariableNames = cellstr(selected);
metadata = readtable(csvPath, opts);
required = ["initial_state_id", "path_id", "sample_weight", "dataset_role"];
fieldsPass = all(ismember(required, string(metadata.Properties.VariableNames)));
stateCountPass = height(metadata) == 525000 && ...
    numel(unique(metadata.initial_state_id)) == 35;
weightPass = true;
for stateId = 1:35
    mask = double(metadata.initial_state_id) == stateId;
    weightPass = weightPass && sum(mask) == 15000 && ...
        max(abs(double(metadata.sample_weight(mask)) - 1 / 15000)) <= 1e-15 && ...
        abs(sum(double(metadata.sample_weight(mask))) - 1) <= 1e-12;
end
probabilityNames = names(contains(lower(names), "probability") | ...
    contains(lower(names), "transition_prob") | ...
    contains(lower(names), "path_prob") | contains(lower(names), "scenario_prob"));
m = matfile(matPath);
matInfo = whos(m);
matNames = string({matInfo.name});
explicitProbability = ~isempty(probabilityNames) || ...
    any(contains(lower(matNames), "probability"));
audit = struct('row_count', height(metadata), 'state_count', ...
    numel(unique(metadata.initial_state_id)), 'rows_per_state', 15000, ...
    'sample_weight_value', 1 / 15000, 'weight_sum_per_state', 1, ...
    'scenario_csv_fields', join(names, ", "), ...
    'dac_mat_fields', join(matNames, ", "), ...
    'explicit_probability_fields', join(probabilityNames, ", "), ...
    'explicit_probability_present', explicitProbability, ...
    'path_id_is_record_identity', true, ...
    'repeated_rows_represent_empirical_mass', true, ...
    'dataset_role_unique', join(unique(metadata.dataset_role), ", "));
pass = fieldsPass && stateCountPass && weightPass && ...
    ~explicitProbability && all(metadata.dataset_role == "nominal");
end

function [data, profileTbl, tailTbl, stateSummaryTbl] = ...
        build_all_state_features(matPath, Cap, M, featureNames, ...
        checkpointDir, config)
totalRows = config.stateCount * config.rowsPerState;
Z = zeros(totalRows, numel(featureNames));
tail95 = false(totalRows, 1);
tail99 = false(totalRows, 1);
tail995 = false(totalRows, 1);
pathId = zeros(totalRows, 1);
profileRecords = cell(0, 1);
tailRecords = cell(0, 1);
summaryRecords = cell(0, 1);
m = matfile(matPath);
for stateId = 1:config.stateCount
    cp = fullfile(checkpointDir, sprintf('features_state_%02d.mat', stateId));
    if isfile(cp)
        loaded = load(cp, 'stateFeature');
        stateFeature = loaded.stateFeature;
        fprintf('Step-03S state %d feature checkpoint loaded.\n', stateId);
    else
        fprintf('Step-03S state %d/35: build 16 risk-decision features.\n', stateId);
        rows = (stateId - 1) * config.rowsPerState + (1:config.rowsPerState);
        D = double(m.D_node_kg(rows, :));
        A = double(m.A_site_node(rows, :, :));
        C = double(m.C_site_node_km(rows, :, :));
        statePathId = double(m.path_id(rows, 1));
        stateIds = double(m.initial_state_id(rows, 1));
        if any(stateIds ~= stateId) || ~isequal(size(A), [15000, 4, 33]) || ...
                ~isequal(size(C), size(A))
            error('Step-03S frozen state %d layout mismatch.', stateId);
        end
        stateFeature = compute_state_feature(stateId, D, A, C, ...
            statePathId, Cap, M, config);
        save(cp, 'stateFeature', '-v7.3');
    end
    rows = (stateId - 1) * config.rowsPerState + (1:config.rowsPerState);
    Z(rows, :) = stateFeature.Z;
    tail95(rows) = stateFeature.tail95;
    tail99(rows) = stateFeature.tail99;
    tail995(rows) = stateFeature.tail995;
    pathId(rows) = stateFeature.path_id;
    for ff = 1:numel(featureNames)
        profileRecords{end + 1, 1} = feature_profile_record( ...
            stateId, featureNames(ff), stateFeature.Z(:, ff)); %#ok<AGROW>
    end
    for rr = 1:numel(stateFeature.tail_records)
        tailRecords{end + 1, 1} = stateFeature.tail_records{rr}; %#ok<AGROW>
    end
    summaryMetricNames = ["unique_D_count", "unique_A_count", ...
        "unique_Ctilde_count", "unique_joint_D_A_Ctilde_count", ...
        "zero_demand_share", "fully_unreachable_demand_share", ...
        "full_capacity_positive_loss_share", ...
        "tail95_threshold_loss_T50", "tail99_threshold_loss_T50", ...
        "tail995_threshold_loss_T50", "tail95_boundary_tie_count", ...
        "tail99_boundary_tie_count", "tail995_boundary_tie_count"];
    for mm = 1:numel(summaryMetricNames)
        metricName = char(summaryMetricNames(mm));
        profileRecords{end + 1, 1} = scalar_profile_record( ...
            stateId, "audit_" + summaryMetricNames(mm), ...
            stateFeature.summary.(metricName)); %#ok<AGROW>
    end
    summaryRecords{end + 1, 1} = stateFeature.summary; %#ok<AGROW>
end
data = struct('Z', Z, 'tail95', tail95, 'tail99', tail99, ...
    'tail995', tail995, 'path_id', pathId);
profileTbl = records_to_table(profileRecords);
tailTbl = records_to_table(tailRecords);
stateSummaryTbl = records_to_table(summaryRecords);
end

function out = compute_state_feature(stateId, D, A, C, pathId, Cap, M, config)
R = size(D, 1);
totalD = sum(D, 2);
unreachableAll = reshape(all(A <= 0.5, 2), R, size(D, 2));
unreachableD = sum(D .* unreachableAll, 2);
unreachableRatio = unreachableD ./ max(totalD, eps);
reachableD = zeros(R, 4);
weightedC = zeros(R, 4);
siteUnreachableD = zeros(R, 4);
for ii = 1:4
    Ai = reshape(A(:, ii, :), R, size(D, 2));
    Ci = reshape(C(:, ii, :), R, size(D, 2));
    Ci(~isfinite(Ci) | Ai <= 0.5) = 0;
    reachableD(:, ii) = sum(Ai .* D, 2);
    denominator = reachableD(:, ii);
    weightedC(:, ii) = sum(Ai .* D .* Ci, 2) ./ max(denominator, eps);
    weightedC(denominator <= eps, ii) = 0;
    siteUnreachableD(:, ii) = sum((Ai <= 0.5) .* D, 2);
end
fractions = [0, 0.25, 0.5, 0.75, 1];
anchorLoss = zeros(R, numel(fractions));
for ff = 1:numel(fractions)
    ev = evaluate_step03P_fixed_T_losses_h2( ...
        D, A, C, fractions(ff) .* Cap, M, config);
    if ev.exitflag ~= 1
        error('Step-03S fixed-T loss evaluation failed at fraction %.2f.', ...
            fractions(ff));
    end
    anchorLoss(:, ff) = ev.loss;
end
Z = [totalD, unreachableD, unreachableRatio, reachableD, weightedC, anchorLoss];
[tail95, threshold95, tie95] = ranked_tail(anchorLoss(:, 3), ...
    config.tail95Count);
[tail99, threshold99, tie99] = ranked_tail(anchorLoss(:, 3), ...
    config.tail99Count);
[tail995, threshold995, tie995] = ranked_tail(anchorLoss(:, 3), ...
    config.tail995Count);

Aflat = reshape(A, R, []);
Ccanonical = reshape(C, R, []);
Ccanonical(~isfinite(Ccanonical) | Aflat <= 0.5) = -1;
uniqueD = size(unique(D, 'rows'), 1);
uniqueA = size(unique(Aflat, 'rows'), 1);
uniqueCtilde = size(unique([Aflat, Ccanonical], 'rows'), 1);
uniqueJoint = size(unique([D, Aflat, Ccanonical], 'rows'), 1);

tailLoss = anchorLoss(tail995, 3);
tailUnreachableNode = mean(D(tail995, :) .* unreachableAll(tail995, :), 1);
[~, affectedNode] = max(tailUnreachableNode);
tailSiteUnreachable = mean(siteUnreachableD(tail995, :), 1);
[~, affectedSite] = max(tailSiteUnreachable);
tailRecords = cell(0, 1);
tailSets = {tail95, tail99, tail995};
tailLabels = ["q95", "q99", "q99.5"];
for tt = 1:3
    mask = tailSets{tt};
    tailRecords{end + 1, 1} = struct('initial_state_id', stateId, ...
        'tail_level', tailLabels(tt), 'record_type', "overall", ...
        'entity_id', 0, 'tail_count', sum(mask), ...
        'mean_value', mean(anchorLoss(mask, 3)), ...
        'maximum_value', max(anchorLoss(mask, 3)), ...
        'share_or_score', sum(mask) / R); %#ok<AGROW>
    for nn = 1:size(D, 2)
        tailRecords{end + 1, 1} = struct('initial_state_id', stateId, ...
            'tail_level', tailLabels(tt), 'record_type', "affected_node", ...
            'entity_id', nn, 'tail_count', sum(mask), ...
