function label = classify_pair_type(rTail, sTail, rLoss, sLoss, dT)
if xor(rTail, sTail)
    label = "NONTAIL_TAIL";
elseif rTail && sTail
    label = "TAIL_TAIL";
elseif abs(rLoss - sLoss) <= 0.01 * max(max(abs([rLoss, sLoss])), 1) && ...
        dT >= 0.25
    label = "SIMILAR_LOSS_DIFFERENT_LAYOUT";
else
    label = "OTHER_NEIGHBOR";
end
end

function [falseTbl, lines] = classify_false_near(crossTbl, config)
severity = min(crossTbl.relative_regret_obj_r_to_s, ...
    crossTbl.relative_regret_obj_s_to_r) ./ max(crossTbl.d_new, 1e-9);
[~, order] = sortrows([-severity, crossTbl.initial_state_id, ...
    crossTbl.scenario_r, crossTbl.scenario_s], [1, 2, 3, 4]);
topCount = min(20, height(crossTbl));
topMask = false(height(crossTbl), 1);
topMask(order(1:topCount)) = true;
keep = crossTbl.tier_1 | topMask;
falseTbl = crossTbl(keep, :);
falseTbl.severity_score = severity(keep);
falseTbl.top20_severity = topMask(keep);
falseTbl.diagnostic_classification = strings(height(falseTbl), 1);
falseTbl.local_average_dilution_flag = false(height(falseTbl), 1);
falseTbl.actual_substitutability = strings(height(falseTbl), 1);
for rr = 1:height(falseTbl)
    bothHigh = falseTbl.relative_regret_obj_r_to_s(rr) >= ...
        config.tierRelative10 && ...
        falseTbl.relative_regret_obj_s_to_r(rr) >= config.tierRelative10;
    oneHigh = max(falseTbl.relative_regret_obj_r_to_s(rr), ...
        falseTbl.relative_regret_obj_s_to_r(rr)) >= config.tierRelative10;
    bothSmall = max(falseTbl.relative_regret_obj_r_to_s(rr), ...
        falseTbl.relative_regret_obj_s_to_r(rr)) < config.tierRelative5;
    dilution = falseTbl.local_dilution_ratio(rr) >= 5 && ...
        falseTbl.changed_local_count(rr) <= 10;
    falseTbl.local_average_dilution_flag(rr) = dilution;
    if falseTbl.tier_0(rr)
        classification = "ZERO_DISTANCE_POSITIVE_REGRET_ERROR";
    elseif bothHigh
        classification = "TRUE_BIDIRECTIONAL_FALSE_NEAR";
    elseif oneHigh
        classification = "ONE_WAY_DOMINANCE_OR_CONTAINMENT";
    elseif bothSmall && falseTbl.d_T_normalized(rr) >= 0.25
        classification = "LARGE_T_SWITCH_BUT_SUBSTITUTABLE";
    elseif dilution
        classification = "LOCAL_CHANGE_DILUTED_BUT_REGRET_LIMITED";
    else
        classification = "NEAR_PAIR_WITH_LIMITED_REGRET";
    end
    falseTbl.diagnostic_classification(rr) = classification;
    if bothHigh
        falseTbl.actual_substitutability(rr) = "NOT_SUBSTITUTABLE";
    elseif oneHigh
        falseTbl.actual_substitutability(rr) = "ASYMMETRIC_SUBSTITUTION";
    else
        falseTbl.actual_substitutability(rr) = "PRACTICALLY_SUBSTITUTABLE";
    end
end
lines = ["## Fixed criteria"; ""; ...
    "Tier-0: d_new=0 and either objective regret exceeds 1e-8."; ...
    "Tier-1: nearest-10 and both relative objective regrets are at least 10%."; ...
    "Tier-2: nearest-10 and at least one relative objective regret is at least 10%."; ...
    "Tier-3: nearest-10 and both relative objective regrets are at least 5%."; ...
    "The historical Step-03R lowest-1% distance and highest-1% decision/loss rule is retained separately."; ""; ...
    "## Required pair diagnostics"; ""];
for rr = 1:height(falseTbl)
    lines(end + 1) = "- state " + falseTbl.initial_state_id(rr) + ...
        ", pair (" + falseTbl.scenario_r(rr) + "," + ...
        falseTbl.scenario_s(rr) + "), type=" + falseTbl.pair_type(rr) + ...
        ", d_D/d_Ctilde/d_new=" + sprintf('%.6g/%.6g/%.6g', ...
        falseTbl.d_D(rr), falseTbl.d_Ctilde(rr), falseTbl.d_new(rr)) + ...
        ", relative regret r->s/s->r=" + sprintf('%.6g/%.6g', ...
        falseTbl.relative_regret_obj_r_to_s(rr), ...
        falseTbl.relative_regret_obj_s_to_r(rr)) + ...
        ", max D-change node=" + falseTbl.max_D_difference_node_id(rr) + ...
        ", A changes=" + falseTbl.A_reachability_change_count(rr) + ...
        ", classification=" + ...
        falseTbl.diagnostic_classification(rr) + "."; %#ok<AGROW>
end
lines = [lines; ""; ...
    "Every row is an equal-mass empirical nominal record. No explicit path/scenario probability exists in Step-03J, so tail rank is not relabeled as a low-probability event."; ...
    "Large T-vector differences with small bidirectional regret are treated as optimizer switching with practical substitutability. One-way high regret is reported as containment/dominance. Only bidirectional high regret is a true decision false-near candidate."];
end

function decision = choose_decision(crossTbl, audit)
if audit.tier0_count > 0
    decision = "D. CTILDE_DISTANCE_REDESIGN_REQUIRED";
elseif audit.tier1_count == 0
    decision = "A. CTILDE_DISTRIBUTION_AND_TAIL_FIT_VALIDATED";
else
    tierStates = numel(unique(crossTbl.initial_state_id(crossTbl.tier_1)));
    if audit.tier1_count <= 3 && tierStates <= 2
        decision = "B. CTILDE_VALID_WITH_ISOLATED_TAIL_FALSE_NEAR";
    else
        tierRows = crossTbl(crossTbl.tier_1, :);
        dilutedShare = mean(tierRows.local_dilution_ratio >= 5 & ...
            tierRows.changed_local_count <= 10);
        if dilutedShare >= 0.5
            decision = "C. CTILDE_REWEIGHTING_REQUIRED";
        else
            decision = "D. CTILDE_DISTANCE_REDESIGN_REQUIRED";
        end
    end
end
end

