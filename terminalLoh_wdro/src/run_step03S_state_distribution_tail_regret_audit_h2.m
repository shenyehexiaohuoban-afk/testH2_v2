function value = pct(x, probability)
x = sort(double(x(:)));
if isempty(x)
    value = NaN;
    return;
end
position = 1 + (numel(x) - 1) * probability;
lowerIndex = floor(position);
upperIndex = ceil(position);
if lowerIndex == upperIndex
    value = x(lowerIndex);
else
    value = x(lowerIndex) + (position - lowerIndex) * ...
        (x(upperIndex) - x(lowerIndex));
end
end

function value = tail_mean(x, probability)
threshold = pct(x, probability);
tail = x(x >= threshold);
if isempty(tail)
    value = threshold;
else
    value = mean(tail);
end
end

function records = table_to_records(tbl)
records = cell(height(tbl), 1);
for rr = 1:height(tbl)
    item = struct();
    for vv = 1:width(tbl)
        name = tbl.Properties.VariableNames{vv};
        value = tbl.(name)(rr, :);
        if iscell(value)
            value = value{1};
        end
        item.(name) = value;
    end
    records{rr} = item;
end
end

function tbl = records_to_table(records)
if isempty(records)
    tbl = table();
else
    tbl = struct2table(vertcat(records{:}));
end
end

function values = hash_files(files)
values = strings(numel(files), 1);
for ii = 1:numel(files)
    if ~isfile(files(ii))
        values(ii) = "MISSING";
    else
        values(ii) = sha256_file(files(ii));
    end
end
end

function value = directory_hash(path)
if ~isfolder(path)
    value = "MISSING";
    return;
end
files = dir(fullfile(path, '**', '*'));
files = files(~[files.isdir]);
relative = strings(numel(files), 1);
for ii = 1:numel(files)
    relative(ii) = replace(string(fullfile(files(ii).folder, files(ii).name)), ...
        string(path) + filesep, "");
end
[relative, order] = sort(relative);
payload = strings(numel(order), 1);
for ii = 1:numel(order)
    filePath = fullfile(path, relative(ii));
    payload(ii) = relative(ii) + "|" + string(files(order(ii)).bytes) + ...
        "|" + sha256_file(filePath);
end
value = sha256_text(join(payload, newline));
end

function value = sha256_file(path)
stream = java.io.FileInputStream(java.io.File(char(path)));
cleanup = onCleanup(@() stream.close());
value = lower(string(org.apache.commons.codec.digest.DigestUtils.sha256Hex(stream)));
clear cleanup;
end

function value = sha256_text(textValue)
bytes = unicode2native(char(textValue), 'UTF-8');
value = lower(string(org.apache.commons.codec.digest.DigestUtils.sha256Hex(bytes)));
end

function value = pass_fail(condition)
if condition
    value = 'PASS';
else
    value = 'FAIL';
end
end

function text = range_text(x)
text = "[" + sprintf('%.12g', min(x)) + "," + ...
    sprintf('%.12g', max(x)) + "]";
end

function write_lines(path, lines)
fid = fopen(path, 'w');
if fid < 0
    error('Step-03S cannot open output file %s.', path);
end
cleanup = onCleanup(@() fclose(fid));
for ii = 1:numel(lines)
    fprintf(fid, '%s\n', lines(ii));
end
clear cleanup;
end
