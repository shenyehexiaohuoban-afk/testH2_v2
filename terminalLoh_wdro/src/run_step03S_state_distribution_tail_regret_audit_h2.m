function Dscale = exact_l1_diameter(D, blockSize)
uniqueD = unique(D, 'rows');
Dscale = 0;
for iStart = 1:blockSize:size(uniqueD, 1)
    iIdx = iStart:min(size(uniqueD, 1), iStart + blockSize - 1);
    Xi = reshape(uniqueD(iIdx, :), [numel(iIdx), 1, size(D, 2)]);
    for jStart = iStart:blockSize:size(uniqueD, 1)
        jIdx = jStart:min(size(uniqueD, 1), jStart + blockSize - 1);
        Xj = reshape(uniqueD(jIdx, :), [1, numel(jIdx), size(D, 2)]);
        block = sum(abs(Xi - Xj), 3);
        Dscale = max(Dscale, max(block, [], 'all'));
    end
end
end

function signature = build_spatial_signature(D, A)
R = size(D, 1);
allUnreachable = reshape(all(A <= 0.5, 2), R, size(D, 2));
[~, nodeMode] = max(D .* allUnreachable, [], 2);
siteUnavailable = zeros(R, 4);
for ii = 1:4
    Ai = reshape(A(:, ii, :), R, size(D, 2));
    siteUnavailable(:, ii) = sum((Ai <= 0.5) .* D, 2);
end
[~, siteMode] = max(siteUnavailable, [], 2);
signature = [siteMode, nodeMode];
end

function tbl = find_tail_neighbors(stateId, D, A, C, pathId, loss50, ...
        tail95, tail99, tail995, spatialSignature, Dscale, config)
query = find(tail95);
nq = numel(query);
categories = ["all", "non_tail", "tail", "loss_similar_spatial"];
bestDistance = cell(numel(categories), 1);
bestIndex = cell(numel(categories), 1);
for cc = 1:numel(categories)
    bestDistance{cc} = inf(nq, config.nearestCount);
    bestIndex{cc} = zeros(nq, config.nearestCount);
end
lossScale = max(max(loss50) - min(loss50), 1);
for qStart = 1:config.distanceQueryBlockSize:nq
    qPos = qStart:min(nq, qStart + config.distanceQueryBlockSize - 1);
    qIdx = query(qPos);
    localBestDistance = cellfun(@(x) x(qPos, :), bestDistance, ...
        'UniformOutput', false);
    localBestIndex = cellfun(@(x) x(qPos, :), bestIndex, ...
        'UniformOutput', false);
    for tStart = 1:config.distanceTargetBlockSize:size(D, 1)
        tIdx = tStart:min(size(D, 1), ...
            tStart + config.distanceTargetBlockSize - 1);
        [distanceBlock, ~, ~] = step03S_distance_block_h2( ...
            D(qIdx, :), A(qIdx, :, :), C(qIdx, :, :), ...
            D(tIdx, :), A(tIdx, :, :), C(tIdx, :, :), ...
            Dscale, config);
        qColumn = qIdx(:);
        targetRow = tIdx(:).';
        selfMask = qColumn == targetRow;
        distanceBlock(selfMask) = Inf;
        categoryMask = cell(numel(categories), 1);
        categoryMask{1} = true(size(distanceBlock));
        categoryMask{2} = repmat((~tail95(tIdx)).', numel(qIdx), 1);
        categoryMask{3} = repmat(tail95(tIdx).', numel(qIdx), 1);
        lossClose = abs(loss50(qColumn) - loss50(targetRow).') <= ...
            config.lossSimilarityFraction * lossScale;
        spatialDifferent = spatialSignature(qColumn, 1) ~= ...
            spatialSignature(targetRow, 1).' | ...
            spatialSignature(qColumn, 2) ~= spatialSignature(targetRow, 2).';
        categoryMask{4} = lossClose & spatialDifferent;
        for cc = 1:numel(categories)
            candidate = distanceBlock;
            candidate(~categoryMask{cc}) = Inf;
            [localBestDistance{cc}, localBestIndex{cc}] = merge_top_k( ...
                localBestDistance{cc}, localBestIndex{cc}, ...
                candidate, tIdx, config.nearestCount);
        end
    end
    for cc = 1:numel(categories)
        bestDistance{cc}(qPos, :) = localBestDistance{cc};
        bestIndex{cc}(qPos, :) = localBestIndex{cc};
    end
    fprintf('  state %d neighbor queries %d/%d complete.\n', ...
        stateId, qPos(end), nq);
end
records = cell(0, 1);
for cc = 1:numel(categories)
    for qq = 1:nq
        r = query(qq);
        valid = isfinite(bestDistance{cc}(qq, :)) & ...
            bestIndex{cc}(qq, :) > 0;
        for rank = find(valid)
            s = bestIndex{cc}(qq, rank);
            [dNew, dD, dC, detail] = step03S_distance_block_h2( ...
                D(r, :), A(r, :, :), C(r, :, :), ...
                D(s, :), A(s, :, :), C(s, :, :), Dscale, config);
            records{end + 1, 1} = struct('initial_state_id', stateId, ...
                'neighbor_category', categories(cc), ...
                'neighbor_rank', rank, 'scenario_r', r, ...
                'path_id_r', pathId(r), 'scenario_s', s, ...
                'path_id_s', pathId(s), 'r_tail95', tail95(r), ...
                'r_tail99', tail99(r), 'r_tail995', tail995(r), ...
                's_tail95', tail95(s), 's_tail99', tail99(s), ...
                's_tail995', tail995(s), 'loss_T50_r', loss50(r), ...
                'loss_T50_s', loss50(s), 'd_D', dD, ...
                'd_Ctilde', dC, 'd_new', dNew, ...
                'max_local_Ctilde', detail.max_local_Ctilde, ...
                'changed_local_count', detail.changed_local_count, ...
                'D_scale', Dscale); %#ok<AGROW>
        end
    end
end
tbl = records_to_table(records);
end

function [bestD, bestI] = merge_top_k(bestD, bestI, blockD, targetIdx, k)
candidateD = [bestD, blockD];
candidateI = [bestI, repmat(targetIdx, size(blockD, 1), 1)];
[sortedD, order] = sort(candidateD, 2, 'ascend');
order = order(:, 1:k);
bestD = sortedD(:, 1:k);
row = repmat((1:size(candidateI, 1)).', 1, k);
bestI = candidateI(sub2ind(size(candidateI), row, order));
end

function atom = solve_required_atoms(D, A, C, indices, Cap, M, config)
n = numel(indices);
T = NaN(n, 4);
objStar = NaN(n, 1);
representativeObj = NaN(n, 1);
rangeWidth = NaN(n, 4);
allOptimal = true;
for start = 1:config.variableLossChunkSize:n
    pos = start:min(n, start + config.variableLossChunkSize - 1);
    idx = indices(pos);
    single = solve_step03R_single_scenario_batch_h2( ...
        D(idx, :), A(idx, :, :), C(idx, :, :), Cap, M, config);
    ranges = solve_step03R_single_scenario_ranges_h2( ...
        D(idx, :), A(idx, :, :), C(idx, :, :), Cap, M, ...
        single.obj_star, config);
    allOptimal = allOptimal && single.exitflag == 1 && ranges.exitflag == 1;
    if ~allOptimal
        break;
    end
    T(pos, :) = single.T;
    objStar(pos) = single.obj_star;
    representativeObj(pos) = single.primary_objective_at_representative;
    rangeWidth(pos, :) = ranges.range_width;
end
atom = struct('indices', indices, 'T', T, 'obj_star', objStar, ...
    'representative_objective', representativeObj, ...
    'range_width', rangeWidth, 'all_optimal', allOptimal);
end

function tbl = build_cross_regret(stateId, D, A, C, pathId, loss50, ...
        tail95, tail99, tail995, neighbor, pairIndex, requiredScenarios, ...
        atom, Cap, M, Dscale, config)
scenarioPosition = zeros(size(D, 1), 1);
scenarioPosition(requiredScenarios) = 1:numel(requiredScenarios);
nPairs = size(pairIndex, 1);
r = pairIndex(:, 1);
s = pairIndex(:, 2);
rPos = scenarioPosition(r);
sPos = scenarioPosition(s);
if any(rPos == 0 | sPos == 0)
    error('Step-03S cross-regret atom mapping is incomplete.');
end
crossLossRtoS = variable_loss_in_chunks(D(s, :), A(s, :, :), ...
    C(s, :, :), atom.T(rPos, :), M, config);
crossLossStoR = variable_loss_in_chunks(D(r, :), A(r, :, :), ...
    C(r, :, :), atom.T(sPos, :), M, config);
ownLossR = atom.representative_objective(rPos) - ...
    config.gamma .* sum(atom.T(rPos, :), 2);
ownLossS = atom.representative_objective(sPos) - ...
    config.gamma .* sum(atom.T(sPos, :), 2);
crossObjRtoS = config.gamma .* sum(atom.T(rPos, :), 2) + crossLossRtoS;
crossObjStoR = config.gamma .* sum(atom.T(sPos, :), 2) + crossLossStoR;
regretObjRtoS = crossObjRtoS - atom.representative_objective(sPos);
regretObjStoR = crossObjStoR - atom.representative_objective(rPos);
regretLossRtoS = crossLossRtoS - ownLossS;
regretLossStoR = crossLossStoR - ownLossR;
relativeRtoS = regretObjRtoS ./ ...
    max(abs(atom.representative_objective(sPos)), 1e-8);
relativeStoR = regretObjStoR ./ ...
    max(abs(atom.representative_objective(rPos)), 1e-8);

records = cell(nPairs, 1);
for pp = 1:nPairs
    pairRows = neighbor(neighbor.scenario_r == r(pp) & ...
        neighbor.scenario_s == s(pp), :);
    categories = join(unique(pairRows.neighbor_category), ";");
    allRanks = pairRows.neighbor_rank(pairRows.neighbor_category == "all");
    if isempty(allRanks)
        allRank = NaN;
        nearestAll = false;
    else
        allRank = min(allRanks);
        nearestAll = allRank <= config.nearestCount;
    end
    [dNew, dD, dC, detail] = step03S_distance_block_h2( ...
        D(r(pp), :), A(r(pp), :, :), C(r(pp), :, :), ...
        D(s(pp), :), A(s(pp), :, :), C(s(pp), :, :), Dscale, config);
    Ddiff = abs(D(r(pp), :) - D(s(pp), :));
    [maxNodeDdiff, maxNode] = max(Ddiff);
    Ar = reshape(A(r(pp), :, :), 4, 33);
    As = reshape(A(s(pp), :, :), 4, 33);
    Cr = reshape(C(r(pp), :, :), 4, 33);
    Cs = reshape(C(s(pp), :, :), 4, 33);
    common = Ar > 0.5 & As > 0.5;
    Ccommon = abs(Cr - Cs);
    Ccommon(~common | ~isfinite(Ccommon)) = 0;
    Tdiff = abs(atom.T(rPos(pp), :) - atom.T(sPos(pp), :));
    [maxSiteTdiff, maxSite] = max(Tdiff);
    dT = mean(Tdiff ./ Cap.');
    tier0 = dNew <= config.zeroDistanceTolerance && ...
        max(regretObjRtoS(pp), regretObjStoR(pp)) > config.regretTolerance;
    tier1 = nearestAll && relativeRtoS(pp) >= config.tierRelative10 && ...
        relativeStoR(pp) >= config.tierRelative10;
    tier2 = nearestAll && max(relativeRtoS(pp), relativeStoR(pp)) >= ...
        config.tierRelative10;
    tier3 = nearestAll && relativeRtoS(pp) >= config.tierRelative5 && ...
        relativeStoR(pp) >= config.tierRelative5;
    pairType = classify_pair_type(tail95(r(pp)), tail95(s(pp)), ...
        loss50(r(pp)), loss50(s(pp)), dT);
    localMeanChanged = dC * 132 / ...
        max(detail.changed_local_count, 1);
    dilutionRatio = detail.max_local_Ctilde / max(localMeanChanged, eps);
    records{pp} = struct('initial_state_id', stateId, ...
        'scenario_r', r(pp), 'path_id_r', pathId(r(pp)), ...
        'scenario_s', s(pp), 'path_id_s', pathId(s(pp)), ...
        'neighbor_categories', categories, 'nearest_all_rank', allRank, ...
        'pair_type', pairType, 'r_tail95', tail95(r(pp)), ...
        'r_tail99', tail99(r(pp)), 'r_tail995', tail995(r(pp)), ...
        's_tail95', tail95(s(pp)), 's_tail99', tail99(s(pp)), ...
        's_tail995', tail995(s(pp)), 'loss_T50_r', loss50(r(pp)), ...
        'loss_T50_s', loss50(s(pp)), 'd_D', dD, ...
        'd_Ctilde', dC, 'd_new', dNew, ...
        'D_l1_difference_kg', sum(Ddiff), ...
        'max_D_difference_node_id', maxNode, ...
        'max_D_difference_kg', maxNodeDdiff, ...
        'A_reachability_change_count', sum(Ar ~= As, 'all'), ...
        'C_common_reachable_l1_km', sum(Ccommon, 'all'), ...
        'changed_local_count', detail.changed_local_count, ...
        'max_local_Ctilde', detail.max_local_Ctilde, ...
        'local_dilution_ratio', dilutionRatio, ...
        'T_r1', atom.T(rPos(pp), 1), 'T_r2', atom.T(rPos(pp), 2), ...
        'T_r3', atom.T(rPos(pp), 3), 'T_r4', atom.T(rPos(pp), 4), ...
        'T_s1', atom.T(sPos(pp), 1), 'T_s2', atom.T(sPos(pp), 2), ...
        'T_s3', atom.T(sPos(pp), 3), 'T_s4', atom.T(sPos(pp), 4), ...
        'd_T_normalized', dT, 'T_L1_difference_kg', sum(Tdiff), ...
        'max_single_site_T_difference_kg', maxSiteTdiff, ...
        'max_difference_site_id', maxSite, ...
        'optimal_objective_r', atom.obj_star(rPos(pp)), ...
        'optimal_objective_s', atom.obj_star(sPos(pp)), ...
        'own_operating_loss_r', ownLossR(pp), ...
        'own_operating_loss_s', ownLossS(pp), ...
        'cross_objective_r_to_s', crossObjRtoS(pp), ...
        'cross_objective_s_to_r', crossObjStoR(pp), ...
        'regret_obj_r_to_s', regretObjRtoS(pp), ...
        'regret_obj_s_to_r', regretObjStoR(pp), ...
        'regret_loss_r_to_s', regretLossRtoS(pp), ...
        'regret_loss_s_to_r', regretLossStoR(pp), ...
        'relative_regret_obj_r_to_s', relativeRtoS(pp), ...
        'relative_regret_obj_s_to_r', relativeStoR(pp), ...
        'multiple_optimum_r', any(atom.range_width(rPos(pp), :) > ...
            config.multipleOptimumWidth), ...
        'multiple_optimum_s', any(atom.range_width(sPos(pp), :) > ...
            config.multipleOptimumWidth), ...
        'capacity_saturated_r', any(atom.T(rPos(pp), :) >= Cap.' - 1e-7), ...
        'capacity_saturated_s', any(atom.T(sPos(pp), :) >= Cap.' - 1e-7), ...
        'tier_0', tier0, 'tier_1', tier1, 'tier_2', tier2, ...
        'tier_3', tier3, 'historical_step03R_false_near', false); 
end
tbl = records_to_table(records);
dCut = pct(tbl.d_new, config.historicalNearFraction);
dTCut = pct(tbl.d_T_normalized, 1 - config.historicalHighFraction);
lossDiff = abs(tbl.loss_T50_r - tbl.loss_T50_s);
lossCut = pct(lossDiff, 1 - config.historicalHighFraction);
tbl.historical_step03R_false_near = tbl.d_new <= dCut & ...
    (tbl.d_T_normalized >= dTCut | lossDiff >= lossCut);
end

function losses = variable_loss_in_chunks(D, A, C, Trows, M, config)
losses = NaN(size(D, 1), 1);
for start = 1:config.variableLossChunkSize:size(D, 1)
    pos = start:min(size(D, 1), start + config.variableLossChunkSize - 1);
    ev = evaluate_step03S_variable_T_losses_h2( ...
        D(pos, :), A(pos, :, :), C(pos, :, :), Trows(pos, :), M, config);
    if ev.exitflag ~= 1
        error('Step-03S variable-T fixed-loss evaluation failed.');
    end
    losses(pos) = ev.loss;
end
end

