scenarioRows = cell(evaluationCount, 39);
for rr = 1:evaluationCount
    idx = evaluationIdentity.recovered_index(rr);
    Dp = squeeze(recovered.Dperiod(idx, :, :));
    Ap = squeeze(recovered.Aperiod(idx, :, :, :));
    Cp = squeeze(recovered.Cperiod(idx, :, :, :));
    Aagg = squeeze(recovered.Aagg(idx, :, :));
    y = squeeze(periodResult.y(rr, :, :, :));
    criticalRelation = false(size(Ap));
    for tau = 1:3
        criticalRelation(tau, :, :) = repmat( ...
            reshape(Dp(tau, :) > demandToleranceKg, [1, 1, model.nNodes]), ...
            [1, model.nSites, 1]);
    end
    aggFalse = repmat(reshape(~Aagg, [1, model.nSites, model.nNodes]), 3, 1, 1);
    maskedReach = Ap & aggFalse & criticalRelation;
    serviceOnMasked = sum(y(maskedReach));
    costOnMasked = sum(Cp(maskedReach) .* y(maskedReach));
    maskedRelationCount = sum(maskedReach, 'all');
    maskedDemand = 0;
    for tau = 1:3
        for nn = 1:model.nNodes
            if Dp(tau, nn) > demandToleranceKg && any(Ap(tau, :, nn), 'all') && ...
                    ~any(Aagg(:, nn))
                maskedDemand = maskedDemand + Dp(tau, nn);
            end
        end
    end
    brokenPairs = 0;
    for nn = 1:model.nNodes
        critical = find(Dp(:, nn) > demandToleranceKg);
        if isempty(critical), critical = (1:3).'; end
        for ii = 1:model.nSites
            pattern = squeeze(Ap(critical, ii, nn));
            brokenPairs = brokenPairs + double(any(pattern) && ~all(pattern));
        end
    end
    qAgg = evaluationIdentity.Q_agg(rr); qPeriod = periodResult.operating_loss(rr);
    signed = qPeriod - qAgg; absDiff = abs(signed);
    relative = absDiff / max([1, abs(qAgg), abs(qPeriod)]);
    if qAgg > qPeriod + numericalTolerance
        direction = "AGGREGATE_OVERESTIMATES";
    elseif qPeriod > qAgg + numericalTolerance
        direction = "AGGREGATE_UNDERESTIMATES";
    else
        direction = "NUMERICALLY_EQUAL";
    end
    scenarioRows(rr, :) = {evaluationIdentity.evaluation_id(rr), ...
        evaluationIdentity.pair_id(rr), evaluationIdentity.pair_group(rr), ...
        evaluationIdentity.initial_state_id(rr), evaluationIdentity.scenario_id(rr), ...
        evaluationIdentity.path_id(rr), evaluationIdentity.scenario_role(rr), ...
        evaluationIdentity.T_source(rr), evaluationIdentity.replay_case(rr), ...
        evaluationIdentity.T1(rr), evaluationIdentity.T2(rr), ...
        evaluationIdentity.T3(rr), evaluationIdentity.T4(rr), qAgg, qPeriod, ...
        signed, absDiff, relative, relative >= largeDifferenceThreshold, direction, ...
        periodResult.service_cost(rr), periodResult.shortage_kg(rr), ...
        periodResult.shortage_loss(rr), periodResult.stage_service_kg(rr, 1), ...
        periodResult.stage_service_kg(rr, 2), periodResult.stage_service_kg(rr, 3), ...
        periodResult.stage_shortage_kg(rr, 1), periodResult.stage_shortage_kg(rr, 2), ...
        periodResult.stage_shortage_kg(rr, 3), periodResult.stage_service_cost(rr, 1), ...
        periodResult.stage_service_cost(rr, 2), periodResult.stage_service_cost(rr, 3), ...
        maskedRelationCount, brokenPairs, maskedDemand, serviceOnMasked, ...
        costOnMasked, serviceOnMasked > numericalTolerance, ...
        relative >= largeDifferenceThreshold && serviceOnMasked > numericalTolerance};
