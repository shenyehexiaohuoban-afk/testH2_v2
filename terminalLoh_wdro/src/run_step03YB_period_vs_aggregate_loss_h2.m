function [recovered, audit] = recover_requested_scenarios(request, nominal, ...
        mainSample, seedMap, windConfig, model, config, baseSeed, ...
        windSeedOffset, rowsPerState, demandToleranceKg)
R = height(request); Dperiod = zeros(R, 3, model.nNodes);
Aperiod = false(R, 3, model.nSites, model.nNodes);
Cperiod = inf(R, 3, model.nSites, model.nNodes);
AaggAll = false(R, model.nSites, model.nNodes);
CaggAll = inf(R, model.nSites, model.nNodes);
DaggAll = zeros(R, model.nNodes); identity = request;
identity.joint_stream_position = zeros(R, 1);
identity.wind_seed = zeros(R, 1); identity.resistance_seed = zeros(R, 1);
identity.final_D_exact = false(R, 1); identity.final_A_exact = false(R, 1);
identity.final_C_exact = false(R, 1); identity.max_DAC_error = inf(R, 1);
streamMatches = 0; sidecar = matfile(config.nominalMat);
for ss = 1:numel(unique(request.initial_state_id))
    stateId = unique(request.initial_state_id); stateId = stateId(ss);
    meta = nominal(double(nominal.initial_state_id) == stateId, :);
    if height(meta) ~= rowsPerState, error('Nominal state block mismatch.'); end
    a0 = double(meta.a0(1)); loc0 = double(meta.loc0(1)); lfw0 = double(meta.lfw0(1));
    stateSample = mainSample(double(mainSample.a0) == a0 & ...
        double(mainSample.loc0) == loc0 & double(mainSample.lfw0) == lfw0, :);
    if height(stateSample) ~= rowsPerState, error('Main-sample state block mismatch.'); end
    resistanceSeed = baseSeed + 100003 * stateId;
    rng(resistanceSeed, 'twister'); permutation = randperm(rowsPerState).';
    lineU = rand(rowsPerState, model.nLines); roadU = rand(rowsPerState, model.nRoads);
    selected = stateSample(permutation, :);
    windSeed = windSeedOffset + baseSeed + 100019 * stateId;
    stream = RandStream('mt19937ar', 'Seed', windSeed); qAll = rand(stream, rowsPerState, 3);
    seedRow = seedMap(double(seedMap.initial_state_id) == stateId, :);
    streamPass = sha256_uint32(permutation) == string(seedRow.step3i_permutation_sha256) && ...
        sha256_double(qAll(:, 1)) == string(seedRow.q_W1_sha256) && ...
        sha256_double(qAll(:, 2)) == string(seedRow.q_W2_sha256) && ...
        sha256_double(qAll(:, 3)) == string(seedRow.q_W3_sha256);
    streamMatches = streamMatches + double(streamPass);
    if ~streamPass, error('Random-stream hash mismatch.'); end
    localIdx = find(request.initial_state_id == stateId);
    for jj = 1:numel(localIdx)
        rr = localIdx(jj); scenarioId = request.scenario_id(rr);
        row = meta(double(meta.scenario_id_in_state) == scenarioId, :);
        if height(row) ~= 1 || double(row.path_id) ~= request.path_id(rr)
            error('Frozen scenario identity mismatch.');
        end
        pos = double(row.joint_stream_position); sample = selected(pos, :);
        if double(sample.path_id) ~= request.path_id(rr), error('Stream mapping mismatch.'); end
        aStage = double([sample.a_W1, sample.a_W2, sample.a_W3]);
        locStage = double([sample.loc_W1, sample.loc_W2, sample.loc_W3]);
        lfwStage = double([sample.lfw_W1, sample.lfw_W2, sample.lfw_W3]);
        pFail = cell(3, 1); pClose = cell(3, 1);
        for tau = 1:3
            vmax = triangular_by_level(aStage(tau), qAll(pos, tau), ...
                windConfig.randomLower, windConfig.randomMode, windConfig.randomUpper);
            idx = state_index(model, aStage(tau), locStage(tau), lfwStage(tau));
            pFail{tau} = compute_line_failure_prob_h2(model.lineFactor(idx, :) .* vmax, model.designWindSpeedVN);
            pClose{tau} = compute_line_failure_prob_h2(model.roadFactor(idx, :) .* vmax, model.roadDesignWindVN);
        end
        failed = false(3, model.nLines); closed = false(3, model.nRoads); slow = zeros(3, model.nRoads);
        failed(1, :) = lineU(pos, :) <= pFail{1};
        failed(2, :) = failed(1, :) | lineU(pos, :) <= pFail{2};
        failed(3, :) = failed(2, :) | lineU(pos, :) <= pFail{3};
        closed(1, :) = roadU(pos, :) <= pClose{1};
        closed(2, :) = closed(1, :) | roadU(pos, :) <= pClose{2};
        closed(3, :) = closed(2, :) | roadU(pos, :) <= pClose{3};
        slow(1, :) = pClose{1}; slow(2, :) = max(slow(1, :), pClose{2});
        slow(3, :) = max(slow(2, :), pClose{3});
        outage = false(3, model.nNodes);
        for tau = 1:3
            outage(tau, :) = double(failed(tau, :)) * model.nodePathIncidence.' > 0;
            outage(tau, model.sourceNode) = false;
        end
        Dtau = double(outage) .* model.Pnode_kW.' * model.DFactorKgPerKWh;
        reachTau = false(3, model.nSites, model.nNodes);
        costTau = inf(3, model.nSites, model.nNodes);
        for tau = 1:3
            edgeCost = model.roadLength .* (1 + slow(tau, :).');
            edgeCost(closed(tau, :).') = Inf;
            [reach, cost] = road_state(model.nNodes, model.roadFrom, model.roadTo, edgeCost, model.siteNodes);
            reachTau(tau, :, :) = reach; costTau(tau, :, :) = cost;
        end
        Dagg = sum(Dtau, 1); Aagg = false(model.nSites, model.nNodes);
        Cagg = inf(model.nSites, model.nNodes);
        for nn = 1:model.nNodes
            critical = find(Dtau(:, nn) > demandToleranceKg);
            if isempty(critical), critical = (1:3).'; end
            for ii = 1:model.nSites
                reach = squeeze(reachTau(critical, ii, nn));
                if all(reach)
                    Aagg(ii, nn) = true;
                    Cagg(ii, nn) = mean(squeeze(costTau(critical, ii, nn)));
                end
            end
        end
        globalRow = (stateId - 1) * rowsPerState + scenarioId;
        Dnom = double(sidecar.D_node_kg(globalRow, :));
        Anom = logical(squeeze(sidecar.A_site_node(globalRow, :, :)));
        Cnom = double(squeeze(sidecar.C_site_node_km(globalRow, :, :)));
        dExact = isequal(Dagg, Dnom); aExact = isequal(Aagg, Anom); cExact = isequaln(Cagg, Cnom);
        finiteBoth = isfinite(Cagg) & isfinite(Cnom); cError = 0;
        if any(finiteBoth, 'all'), cError = max(abs(Cagg(finiteBoth) - Cnom(finiteBoth))); end
        Dperiod(rr, :, :) = Dtau; Aperiod(rr, :, :, :) = reachTau;
        Cperiod(rr, :, :, :) = costTau; DaggAll(rr, :) = Dagg;
        AaggAll(rr, :, :) = Aagg; CaggAll(rr, :, :) = Cagg;
        identity.joint_stream_position(rr) = pos; identity.wind_seed(rr) = windSeed;
        identity.resistance_seed(rr) = resistanceSeed; identity.final_D_exact(rr) = dExact;
        identity.final_A_exact(rr) = aExact; identity.final_C_exact(rr) = cExact;
        identity.max_DAC_error(rr) = max([max(abs(Dagg - Dnom)), cError, ...
            double(sum(Aagg ~= Anom, 'all')), double(sum(isinf(Cagg) ~= isinf(Cnom), 'all'))]);
        if ~(dExact && aExact && cExact), error('Recovered final D/A/C mismatch.'); end
    end
end
recovered = struct('identity', identity, 'Dperiod', Dperiod, 'Aperiod', Aperiod, ...
    'Cperiod', Cperiod, 'Dagg', DaggAll, 'Aagg', AaggAll, 'Cagg', CaggAll);
audit = struct('all_final_DAC_exact', all(identity.final_D_exact & identity.final_A_exact & identity.final_C_exact), ...
    'max_DAC_error', max(identity.max_DAC_error), ...
    'all_stream_hashes_match', streamMatches == numel(unique(request.initial_state_id)), ...
    'stream_match_count', streamMatches);
end

