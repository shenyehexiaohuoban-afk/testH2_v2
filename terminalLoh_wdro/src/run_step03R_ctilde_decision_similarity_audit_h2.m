out = struct('statistics', statistics, ...
    'comparisonRecords', {comparisonRecords}, ...
    'falseNearRecords', {falseNearRecords}, ...
    'counterfactualSelection', {counterfactualSelection}, ...
    'zeroDistanceMaxDT', zeroMaxDT, 'zeroDistanceMaxLoss', zeroMaxLoss, ...
    'nearMedianDT', comparisonRecords{1}.d_T_median, ...
    'farMedianDT', comparisonRecords{3}.d_T_median, ...
    'nearMedianLossProfile', comparisonRecords{1}.d_loss_profile_median, ...
    'farMedianLossProfile', comparisonRecords{3}.d_loss_profile_median);
