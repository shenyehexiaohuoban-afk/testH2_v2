function reason = diagnose_pair(item, r, s, rangeOverlap, falseDecision, falseLoss)
if rangeOverlap && (item.isMultiple(r) || item.isMultiple(s))
    reason = "MULTIPLE_OPTIMA_RANGE_OVERLAP";
elseif item.isFullySaturated(r) && item.isFullySaturated(s)
    reason = "CAPACITY_SATURATION";
elseif item.activeDestinationCount(r) == 0 && item.activeDestinationCount(s) == 0
    reason = "NON_KEY_SCENARIOS_UNDER_STEP03Q_WDRO";
elseif falseDecision || falseLoss
    reason = "TRUE_FALSE_NEAR_CONFLICT";
else
    reason = "LIMITED_NEAR_DIFFERENCE";
end
end

function rec = reconcile_step03Q_near(item, source, destination, deltaT, Cap, config)
dT = mean(abs(item.single.T(source, :) - item.single.T(destination, :)) ./ Cap.');
profileDistance = max(abs(item.lossProfile(source, :) - item.lossProfile(destination, :)));
rangeOverlap = all(max(item.ranges.T_min(source, :), item.ranges.T_min(destination, :)) <= ...
    min(item.ranges.T_max(source, :), item.ranges.T_max(destination, :)) + 1e-7);
wdroFullySaturated = all(item.activitySol.T >= Cap - 1e-7);
if dT <= 1e-6 && profileDistance <= 1e-6
    classification = "TRUE_SCENARIO_SIMILARITY";
elseif wdroFullySaturated
    classification = "CAPACITY_SATURATION";
elseif rangeOverlap && (item.isMultiple(source) || item.isMultiple(destination))
    classification = "MULTIPLE_OPTIMA";
elseif item.activeDestinationCount(source) == 0 && ...
        item.activeDestinationCount(destination) == 0
    classification = "SCENARIOS_NOT_WDRO_KEY";
else
    activeLoss = item.activitySol.L(item.activeDestinationCount > 0);
    pairLoss = item.activitySol.L([source, destination]);
    if ~isempty(activeLoss) && max(activeLoss) > max(pairLoss) + config.primaryObjectiveTolerance
        classification = "DOMINATED_BY_MORE_SEVERE_ACTIVE_SCENARIOS";
    else
        classification = "MIXED_OR_LIMITED_EFFECT";
    end
end
rec = struct('complexity_label', item.state.complexity_label, ...
    'initial_state_id', item.state.initial_state_id, ...
    'source_scenario_index', source, 'destination_scenario_index', destination, ...
    'step03Q_perturbed_T_max_abs_change', deltaT, ...
    'single_scenario_d_T', dT, 'loss_profile_distance', profileDistance, ...
    'optimal_range_overlap_all_sites', rangeOverlap, ...
    'source_multiple_optimum', item.isMultiple(source), ...
    'destination_multiple_optimum', item.isMultiple(destination), ...
    'wdro_solution_fully_saturated', wdroFullySaturated, ...
    'source_fully_saturated', item.isFullySaturated(source), ...
    'destination_fully_saturated', item.isFullySaturated(destination), ...
    'source_active_destination_count', item.activeDestinationCount(source), ...
    'destination_active_destination_count', item.activeDestinationCount(destination), ...
    'classification', classification);
end

function tbl = run_counterfactuals(stateData, selections, Cap, M, config)
flat = cell(0, 1);
for ii = 1:numel(selections)
    current = selections{ii};
    if iscell(current)
        for jj = 1:numel(current)
            flat{end + 1, 1} = current{jj}; %#ok<AGROW>
        end
    else
        flat{end + 1, 1} = current; %#ok<AGROW>
    end
end
keys = strings(numel(flat), 1);
for ii = 1:numel(flat)
    keys(ii) = string(flat{ii}.stateRow) + "_" + ...
        string(min(flat{ii}.source, flat{ii}.destination)) + "_" + ...
        string(max(flat{ii}.source, flat{ii}.destination));
end
[~, keep] = unique(keys, 'stable');
flat = flat(sort(keep));
records = cell(numel(flat), 1);
for ii = 1:numel(flat)
    selection = flat{ii};
    item = stateData{selection.stateRow};
    r = selection.source;
    s = selection.destination;
    localD = item.data.D([r,s], :);
    localA = item.data.A([r,s], :, :);
    localC = item.data.C([r,s], :, :);
    empiricalDistance = [0,1;1,0];
    mixture = solve_step03P_weighted_cg_h2(localD, localA, localC, ...
        Cap, M, 0, empiricalDistance, [0.5;0.5], config);
    if mixture.exitflag ~= 1 || ~mixture.converged
        error('Step-03R two-scenario counterfactual solve failed.');
    end
    dNew = item.dNew(r, s);
    dT = mean(abs(item.single.T(r, :) - item.single.T(s, :)) ./ Cap.');
    profileDistance = max(abs(item.lossProfile(r, :) - item.lossProfile(s, :)));
    records{ii} = struct('complexity_label', item.state.complexity_label, ...
        'initial_state_id', item.state.initial_state_id, ...
        'selection_basis', selection.selectionBasis, ...
        'scenario_r', r, 'path_id_r', item.data.path_id(r), ...
        'scenario_s', s, 'path_id_s', item.data.path_id(s), ...
        'd_new', dNew, 'd_T', dT, 'd_loss_profile', profileDistance, ...
        'T_r1', item.single.T(r, 1), 'T_r2', item.single.T(r, 2), ...
        'T_r3', item.single.T(r, 3), 'T_r4', item.single.T(r, 4), ...
        'T_s1', item.single.T(s, 1), 'T_s2', item.single.T(s, 2), ...
        'T_s3', item.single.T(s, 3), 'T_s4', item.single.T(s, 4), ...
        'T_mix1', mixture.T(1), 'T_mix2', mixture.T(2), ...
        'T_mix3', mixture.T(3), 'T_mix4', mixture.T(4), ...
        'mix_objective_value', mixture.objective_value, ...
        'mix_max_independent_violation', mixture.final_independent_scan_max_violation, ...
        'mix_T_distance_from_r', mean(abs(mixture.T.' - item.single.T(r, :)) ./ Cap.'), ...
        'mix_T_distance_from_s', mean(abs(mixture.T.' - item.single.T(s, :)) ./ Cap.'));
end
tbl = records_to_table(records);
end

