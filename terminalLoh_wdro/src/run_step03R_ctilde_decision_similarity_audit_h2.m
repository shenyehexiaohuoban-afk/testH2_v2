function values = normalized_severity(x, threshold)
values = x ./ max(threshold, eps);
end

function value = spearman_corr(x, y)
rx = average_rank(x);
ry = average_rank(y);
matrix = corrcoef(rx, ry);
value = matrix(1, 2);
end

function ranks = average_rank(x)
[sorted, order] = sort(x(:));
ranks = zeros(size(sorted));
start = 1;
while start <= numel(sorted)
    finish = start;
    while finish < numel(sorted) && sorted(finish + 1) == sorted(start)
        finish = finish + 1;
    end
    ranks(order(start:finish)) = (start + finish) / 2;
    start = finish + 1;
end
end

function value = pct(x, probability)
x = sort(double(x(:)));
if isempty(x)
    value = NaN;
    return;
end
position = 1 + (numel(x) - 1) * probability;
lower = floor(position);
upper = ceil(position);
if lower == upper
    value = x(lower);
else
    value = x(lower) + (position - lower) * (x(upper) - x(lower));
end
end

