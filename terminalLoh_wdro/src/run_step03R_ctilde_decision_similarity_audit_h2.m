        ", mix distance from r/s=" + ...
        string(sprintf('%.6g/%.6g', counterfactual.mix_T_distance_from_r(rr), ...
        counterfactual.mix_T_distance_from_s(rr))) + "."; %#ok<AGROW>
end
write_lines(path, lines);
end

function write_summary(path, decision, ~, comparison, falseNear, ...
        reconciliation, counterfactual, spearmanDecision, spearmanLoss, ...
        zeroMaxDT, zeroMaxLoss, failCount)
near = comparison(comparison.pair_category == "near", :);
far = comparison(comparison.pair_category == "far", :);
replaceAllowed = startsWith(decision, "A.") || startsWith(decision, "B.");
lines = ["Step-03R Ctilde decision-similarity audit"; ""; ...
    "decision=" + decision; ...
    "states=simple 7, medium 18, complex 30; R=2000 each; nominal only"; ...
    "single_scenario_count=6000"; ...
    "spearman_dnew_dT_range=" + range_text(spearmanDecision); ...
    "spearman_dnew_dloss_profile_range=" + range_text(spearmanLoss); ...
    "near_dT_median_range=" + range_text(near.d_T_median); ...
    "far_dT_median_range=" + range_text(far.d_T_median); ...
    "near_loss_profile_median_range=" + range_text(near.d_loss_profile_median); ...
    "far_loss_profile_median_range=" + range_text(far.d_loss_profile_median); ...
    "formal_false_near_count=" + string(height(falseNear)); ...
    "zero_distance_max_dT=" + string(sprintf('%.16g', zeroMaxDT)); ...
    "zero_distance_max_loss_profile=" + string(sprintf('%.16g', zeroMaxLoss)); ...
    "counterfactual_pair_count=" + string(height(counterfactual)); ...
    "mechanical_FAIL=" + string(failCount); ""; ...
    "Required answers:"; ...
    "1. Near single-scenario ideal T is usually closer than far T: " + yes_no(all(near.d_T_median < far.d_T_median)) + "."; ...
    "2. Near complete loss profiles are usually closer than far profiles: " + yes_no(all(near.d_loss_profile_median < far.d_loss_profile_median)) + "."; ...
    "3. Far T differences are materially larger in the median comparison: " + yes_no(all(far.d_T_median > near.d_T_median)) + "."; ...
    "4. Small-distance opposite-layout counterexamples: " + false_near_answer(falseNear) + "."; ...
    "5. Step-03Q near DeltaT explanations: " + join(unique(reconciliation.classification), ", ") + "."; ...
    "6. Complex full capacity masking present: " + yes_no(any(reconciliation.complexity_label == "complex" & reconciliation.wdro_solution_fully_saturated)) + "."; ...
    "7. Multiple optima affect some comparisons: " + yes_no(any(reconciliation.source_multiple_optimum | reconciliation.destination_multiple_optimum)) + "."; ...
    "8. Ctilde reflects pre-layout similarity under this audit: " + yes_no(replaceAllowed) + "."; ...
    "9. Formal replacement recommendation: " + replacement_answer(replaceAllowed) + "."; ...
    "10. Rho recalibration and R=5000 may proceed only after accepted replacement and separate resource protection: " + yes_no(replaceAllowed) + "."; ""; ...
    "Formal distance, kappa, WDRO loss, MSP, Step-03J, Step-03Q, and the untracked Step-03P failed history were not modified."; ...
    "No validation data, scenario reduction, clustering, R=5000, R=15000, or all-35-state run was used."];
write_lines(path, lines);
end

function text = false_near_answer(tbl)
if isempty(tbl)
    text = "none under the specified 1% by 1% definitions";
elseif any(tbl.diagnostic_reason == "TRUE_FALSE_NEAR_CONFLICT")
    text = "yes; see diagnosed true conflicts";
else
    text = "limited candidates exist but are explained by range overlap, saturation, or non-key status";
end
end

function text = replacement_answer(allowed)
if allowed
    text = "supported after freezing the candidate definition and recalibrating rho; this run does not replace it";
else
    text = "not supported by this audit";
end
end

function text = yes_no(condition)
if condition
    text = "YES";
else
    text = "NO";
end
end

function text = range_text(x)
text = "[" + string(sprintf('%.12g', min(x))) + "," + ...
    string(sprintf('%.12g', max(x))) + "]";
end

function write_lines(path, lines)
fid = fopen(path, 'w');
if fid < 0
    error('Step-03R cannot open output file %s.', path);
end
cleanup = onCleanup(@() fclose(fid));
for ii = 1:numel(lines)
    fprintf(fid, '%s\n', lines(ii));
end
end
