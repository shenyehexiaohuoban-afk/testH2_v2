function value = directory_hash(path)
if ~isfolder(path)
    value = "MISSING";
    return;
end
files = dir(fullfile(path, '**', '*'));
files = files(~[files.isdir]);
relative = strings(numel(files), 1);
for ii = 1:numel(files)
    relative(ii) = replace(string(fullfile(files(ii).folder, files(ii).name)), ...
        string(path) + filesep, "");
end
[relative, order] = sort(relative);
payload = strings(numel(order), 1);
for ii = 1:numel(order)
    filePath = fullfile(path, relative(ii));
    payload(ii) = relative(ii) + "|" + string(files(order(ii)).bytes) + ...
        "|" + sha256_file(filePath);
end
value = sha256_text(join(payload, newline));
end

function value = sha256_file(path)
stream = java.io.FileInputStream(java.io.File(char(path)));
cleanup = onCleanup(@() stream.close());
value = lower(string(org.apache.commons.codec.digest.DigestUtils.sha256Hex(stream)));
end

function value = sha256_text(textValue)
bytes = unicode2native(char(textValue), 'UTF-8');
value = lower(string(org.apache.commons.codec.digest.DigestUtils.sha256Hex(bytes)));
end

function value = pass_fail(condition)
if condition
    value = 'PASS';
else
    value = 'FAIL';
end
end

