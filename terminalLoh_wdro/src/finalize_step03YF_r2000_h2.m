function stability = add_stability_diagnostics(stability, stateIds, Cap, ...
        tol, closeCap, closeRegret)
stability.difference_direction = strings(height(stability), 1);
stability.site_direction_stable_across_R = false(height(stability), 1);
stability.reference_dominant_site_R500 = zeros(height(stability), 1);
stability.reference_direction_stable_across_R = false(height(stability), 1);
stability.state_max_site_difference_kg = zeros(height(stability), 1);
stability.state_max_relative_regret = zeros(height(stability), 1);
stability.state_close_diagnostic = false(height(stability), 1);
stability.aggregate_capacity_hit_count = zeros(height(stability), 1);
stability.period_capacity_hit_count = zeros(height(stability), 1);
sampleSizes = [500, 1000, 2000];
for ss = 1:numel(stateIds)
    stateId = stateIds(ss);
    r500 = stability(stability.initial_state_id == stateId & ...
        stability.R == 500, :);
    [~, dominantIndex] = max(r500.site_absolute_difference_kg);
    dominantSite = r500.site_id(dominantIndex);
    dominantDirections = zeros(3, 1);
    for kk = 1:3
        R = sampleSizes(kk);
        rows = stability.initial_state_id == stateId & stability.R == R;
        current = stability(rows, :);
        directions = sign_tol(current.period_minus_aggregate_kg, tol);
        stability.difference_direction(rows) = direction_labels(directions);
        dominantDirections(kk) = directions(current.site_id == dominantSite);
        maxRegret = max([current.aggregate_relative_regret(1), ...
            current.period_relative_regret(1)]);
        close = max(current.site_difference_fraction_of_capacity) <= closeCap && ...
            current.total_difference_fraction_of_total_capacity(1) <= closeCap && ...
            maxRegret <= closeRegret;
        stability.reference_dominant_site_R500(rows) = dominantSite;
        stability.state_max_site_difference_kg(rows) = ...
            max(current.site_absolute_difference_kg);
        stability.state_max_relative_regret(rows) = maxRegret;
        stability.state_close_diagnostic(rows) = close;
        stability.aggregate_capacity_hit_count(rows) = ...
            sum(current.aggregate_at_capacity);
        stability.period_capacity_hit_count(rows) = ...
            sum(current.period_at_capacity);
    end
    stateRows = stability.initial_state_id == stateId;
    stability.reference_direction_stable_across_R(stateRows) = ...
        all(dominantDirections == dominantDirections(1));
    for site = 1:4
        rows = stateRows & stability.site_id == site;
        directions = sign_tol(stability.period_minus_aggregate_kg(rows), tol);
        stability.site_direction_stable_across_R(rows) = ...
            all(directions == directions(1));
    end
end
if any(stability.site_difference_fraction_of_capacity > 1 + tol) || ...
        any(stability.T_aggregate_kg < -tol) || any(stability.T_period_kg < -tol) || ...
        any(stability.T_aggregate_kg - Cap(stability.site_id) > tol) || ...
        any(stability.T_period_kg - Cap(stability.site_id) > tol)
    error('Step-03Y-F stability values violate capacity/finite bounds.');
end
end

function summary = summarize_states(stability, capacity, stateIds, tol)
rows = struct([]);
for ss = 1:numel(stateIds)
    stateId = stateIds(ss);
    data = stability(stability.initial_state_id == stateId, :);
    r500 = data(data.R == 500, :);
    r1000 = data(data.R == 1000, :);
    r2000 = data(data.R == 2000, :);
    site2 = r2000(r2000.site_id == 2, :);
    maxDiff = max(r2000.site_absolute_difference_kg);
    totalDiff = abs(r2000.period_minus_aggregate_total_kg(1));
    if totalDiff / 750 <= 0.10 && ...
            max(r2000.site_difference_fraction_of_capacity) > 0.10
        effectType = "SITE_REALLOCATION_DOMINANT";
    elseif totalDiff / 750 > 0.10
        effectType = "TOTAL_AND_SITE_DIFFER";
    elseif maxDiff <= tol
        effectType = "NUMERICALLY_IDENTICAL";
    else
        effectType = "SMALL_MIXED_DIFFERENCE";
    end
    cap = capacity(capacity.initial_state_id == stateId, :);
    row = struct('initial_state_id', stateId, ...
        'max_site_difference_R500_kg', max(r500.site_absolute_difference_kg), ...
        'max_site_difference_R1000_kg', max(r1000.site_absolute_difference_kg), ...
        'max_site_difference_R2000_kg', maxDiff, ...
        'total_difference_R500_kg', r500.period_minus_aggregate_total_kg(1), ...
        'total_difference_R1000_kg', r1000.period_minus_aggregate_total_kg(1), ...
        'total_difference_R2000_kg', r2000.period_minus_aggregate_total_kg(1), ...
        'site2_difference_R2000_kg', site2.period_minus_aggregate_kg, ...
        'max_relative_regret_R2000', r2000.state_max_relative_regret(1), ...
        'close_R500', r500.state_close_diagnostic(1), ...
        'close_R1000', r1000.state_close_diagnostic(1), ...
        'close_R2000', r2000.state_close_diagnostic(1), ...
        'reference_site_R500', r2000.reference_dominant_site_R500(1), ...
        'reference_direction_stable', ...
        r2000.reference_direction_stable_across_R(1), ...
        'aggregate_capacity_hits_R2000', sum(cap.model == "AGGREGATE" & ...
        cap.at_capacity_upper), ...
        'period_capacity_hits_R2000', sum(cap.model == "PERIOD" & ...
        cap.at_capacity_upper), ...
        'R2000_effect_type', effectType);
    rows = append_struct(rows, row);
end
summary = struct2table(rows);
end

function conclusion = classify_result(summary, effectStateIds)
effect = summary(ismember(summary.initial_state_id, effectStateIds), :);
control = summary(summary.initial_state_id == 7, :);
if all(~effect.close_R2000) && all(effect.reference_direction_stable) && ...
        control.close_R2000
    conclusion = "A. PERIOD_EFFECT_STABLE";
elseif all(effect.close_R2000) && control.close_R2000
    conclusion = "B. AGGREGATE_AND_PERIOD_CONVERGE";
else
    conclusion = "C. STATE_DEPENDENT_OR_UNSTABLE";
end
end

