function values = sign_tol(values, tol)
values(abs(values) <= tol) = 0;
values(values > tol) = 1;
values(values < -tol) = -1;
end

function labels = direction_labels(values)
labels = repmat("ZERO", size(values));
labels(values > 0) = "PERIOD_HIGHER";
labels(values < 0) = "PERIOD_LOWER";
end

