function finalize_step03YF_r2000_h2()
%FINALIZE_STEP03YF_R2000_H2 Combine four isolated R=2000 state runs.

started = tic;
thisFile = mfilename('fullpath');
thisDir = fileparts(thisFile);
moduleDir = fileparts(thisDir);
rootDir = fileparts(moduleDir);
expectedBranch = "task/002-stage2b-b3-smoke";
expectedHead = "f46321afbe78469962f97f26f4f8ccea0329f89d";
stateIds = [7; 9; 11; 19];
effectStateIds = [9; 11; 19];
formalCap = [300; 200; 100; 150];
tolerance = 1e-7;
closeCapacityFraction = 0.10;
closeRelativeRegret = 0.01;
outputBase = fullfile(rootDir, 'results', ...
    'task-002-stage2b-b3-smoke', ...
    '35-period-vs-aggregate-saa-r2000');
workDir = fullfile(outputBase, 'run-001.inprogress');
outputDir = fullfile(outputBase, 'run-001');
finalizingDir = fullfile(outputBase, 'run-001.finalizing');

[~, branch] = system('git branch --show-current');
[~, head] = system('git rev-parse HEAD');
[~, upstream] = system('git rev-parse "@{upstream}"');
[~, statusBefore] = system('git status --short --branch');
branch = string(strtrim(branch));
head = string(strtrim(head));
upstream = string(strtrim(upstream));
statusBefore = string(strtrim(statusBefore));
if branch ~= expectedBranch || head ~= expectedHead || upstream ~= expectedHead
    error('Step-03Y-F frozen Git baseline mismatch.');
end
if ~isfolder(workDir) || isfolder(outputDir) || isfolder(finalizingDir)
    error('Step-03Y-F checkpoint/final path state is invalid.');
end

protectedRelative = protected_paths();
protectedBefore = strings(numel(protectedRelative), 1);
for ii = 1:numel(protectedRelative)
    protectedBefore(ii) = path_digest(fullfile(rootDir, protectedRelative(ii)));
    if protectedBefore(ii) == "MISSING"
        error('Step-03Y-F protected path missing: %s', protectedRelative(ii));
    end
end

terminal = table(); cross = table(); objective = table(); capacity = table();
metrics = table();
for ss = 1:numel(stateIds)
    stateId = stateIds(ss);
    prefix = sprintf('state_%02d', stateId);
    auditFile = fullfile(workDir, prefix + "_audit.txt");
    if ~isfile(auditFile) || ~contains(fileread(auditFile), 'status=PASS')
        error('Step-03Y-F state %d did not complete successfully.', stateId);
    end
    terminal = append_table(terminal, readtable(fullfile(workDir, ...
        prefix + "_terminal.csv"), 'TextType', 'string'));
    cross = append_table(cross, readtable(fullfile(workDir, ...
        prefix + "_cross.csv"), 'TextType', 'string'));
    objective = append_table(objective, readtable(fullfile(workDir, ...
        prefix + "_objective.csv"), 'TextType', 'string'));
    capacity = append_table(capacity, readtable(fullfile(workDir, ...
        prefix + "_capacity.csv"), 'TextType', 'string'));
    metrics = append_table(metrics, readtable(fullfile(workDir, ...
        prefix + "_metrics.csv"), 'TextType', 'string'));
end
terminal = normalize_terminal(terminal);
cross = normalize_cross(cross);
objective = normalize_objective(objective);
capacity = normalize_capacity(capacity);
if height(terminal) ~= 16 || height(cross) ~= 16 || ...
        height(objective) ~= 8 || height(capacity) ~= 32 || ...
        height(metrics) ~= 4 || ~all(terminal.case_pass) || ...
        ~all(cross.case_pass) || ~all(objective.case_pass) || ...
        ~all(capacity.case_pass)
    error('Step-03Y-F R=2000 state checkpoint table audit failed.');
end

stepYEDir = fullfile(rootDir, 'results', ...
    'task-002-stage2b-b3-smoke', ...
    '34-period-vs-aggregate-saa-stability', 'run-001');
