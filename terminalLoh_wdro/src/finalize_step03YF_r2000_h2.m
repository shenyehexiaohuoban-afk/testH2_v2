if ~isfile(stepYEAudit) || ...
        ~contains(fileread(stepYEAudit), 'R1000_is_nominal_prefix=true') || ...
        ~contains(fileread(stepYEAudit), 'deterministic_replay_max_DAC_error=0')
    error('Step-03Y-F requires the mechanically valid Step-03Y-E R=1000 phase.');
end
prior = readtable(fullfile(stepYEDir, ...
    'terminalLOH_stability.csv'), 'TextType', 'string');
prior = prior(ismember(prior.initial_state_id, stateIds) & ...
    ismember(prior.R, [500, 1000]), :);
if height(prior) ~= 32 || ~all(prior.case_pass)
    error('Step-03Y-F R=500/R=1000 prior stability rows are incomplete.');
end
stability = [stability_core(prior); stability_core(terminal)];
stability = add_stability_diagnostics(stability, stateIds, formalCap, ...
    tolerance, closeCapacityFraction, closeRelativeRegret);

summary = summarize_states(stability, capacity, stateIds, tolerance);
conclusion = classify_result(summary, effectStateIds);
solverCallCount = sum(metrics.solver_call_count);
totalStateRuntime = sum(metrics.runtime_sec);
maxStateRuntime = max(metrics.runtime_sec);
overallPeakMemory = max(metrics.peak_working_set_bytes);
if solverCallCount ~= 16 || any(metrics.max_DAC_error ~= 0) || ...
        any(metrics.checkcode_issue_count ~= 0) || ...
        any(~isfinite(metrics.runtime_sec)) || ...
        any(~isfinite(metrics.peak_working_set_bytes))
    error('Step-03Y-F combined metrics audit failed.');
end

protectedAfter = strings(numel(protectedRelative), 1);
for ii = 1:numel(protectedRelative)
    protectedAfter(ii) = path_digest(fullfile(rootDir, protectedRelative(ii)));
end
if ~isequal(protectedBefore, protectedAfter)
    error('Step-03Y-F protected path changed during finalization.');
end
codeFiles = [string(thisFile); ...
    string(fullfile(thisDir, 'run_step03YF_r2000_state_h2.m')); ...
    string(fullfile(thisDir, 'recover_step03Y_prefix_entries_h2.m')); ...
    string(fullfile(thisDir, 'solve_step03Y_saa_audit_h2.m'))];
