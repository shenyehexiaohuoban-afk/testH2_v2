        "_runtime_sec=" + sprintf('%.6f', metrics.runtime_sec(ii)) + ...
        ";peak_bytes=" + sprintf('%.0f', metrics.peak_working_set_bytes(ii)) + ...
        ";solver_calls=" + metrics.solver_call_count(ii); %#ok<AGROW>
end
write_lines(fullfile(finalizingDir, 'mechanical_audit.txt'), auditLines);

conclusionLines = build_conclusion(summary, conclusion, solverCallCount, ...
    totalStateRuntime, overallPeakMemory);
write_lines(fullfile(finalizingDir, 'conclusion.txt'), conclusionLines);
readmeLines = build_readme(summary, conclusion, solverCallCount, ...
    totalStateRuntime, overallPeakMemory, statusBefore);
write_lines(fullfile(finalizingDir, 'README.md'), readmeLines);

rmdir(workDir, 's');
movefile(finalizingDir, outputDir);
append_log(fullfile(rootDir, 'codex_rule', 'log.md'), summary, conclusion, ...
    solverCallCount, totalStateRuntime, overallPeakMemory);
