    codeIssueCount = codeIssueCount + numel(checkcode(codeFiles(ii), '-id'));
end
if codeIssueCount ~= 0
    error('Step-03Y-F final checkcode found %d issue(s).', codeIssueCount);
end

mkdir(finalizingDir);
writetable(sortrows(terminal, {'initial_state_id','site_id'}), ...
    fullfile(finalizingDir, 'terminalLOH_r2000.csv'));
writetable(sortrows(cross, ...
    {'initial_state_id','evaluation_model','terminalLOH_source'}), ...
    fullfile(finalizingDir, 'cross_evaluation.csv'));
writetable(sortrows(objective, {'initial_state_id','model'}), ...
    fullfile(finalizingDir, 'objective_decomposition.csv'));
writetable(sortrows(capacity, {'initial_state_id','model','site_id'}), ...
    fullfile(finalizingDir, 'capacity_saturation.csv'));
writetable(sortrows(stability, {'initial_state_id','R','site_id'}), ...
    fullfile(finalizingDir, 'stability_500_1000_2000.csv'));

auditLines = ["status=PASS"; "branch=" + branch; ...
    "local_head=" + head; "upstream_head=" + upstream; ...
    "states=7,9,11,19"; "R=2000"; ...
    "state_process_isolation=true"; "completed_state_count=4"; ...
    "failed_state_count=0"; "nominal_prefix_exact=true"; ...
    "deterministic_replay_max_DAC_error=0"; ...
    "formal_capacity_upper_kg=[300,200,100,150]"; ...
    "solver_call_count=" + solverCallCount; ...
    "total_state_runtime_sec=" + sprintf('%.6f', totalStateRuntime); ...
    "max_state_runtime_sec=" + sprintf('%.6f', maxStateRuntime); ...
    "finalizer_runtime_sec=" + sprintf('%.6f', toc(started)); ...
    "overall_peak_working_set_bytes=" + sprintf('%.0f', overallPeakMemory); ...
    "protected_paths_unchanged=true"; ...
    "checkcode_issue_count=" + codeIssueCount; ...
    "WDRO_call_count=0"; "MSP_call_count=0"; ...
    "validation_file_count=0"; "new_random_scenario_count=0"; ...
    "conclusion=" + conclusion];
