function validate_stepS_inputs(crossTbl, falseTbl, neighborTbl, ...
        selectedStates, stateProfiles, acceptance, config)
requiredCross = {'initial_state_id', 'scenario_r', 'scenario_s', ...
    'path_id_r', 'path_id_s', 'pair_type', 'nearest_all_rank', ...
    'd_D', 'd_Ctilde', 'd_new', 'T_r1', 'T_r2', 'T_r3', 'T_r4', ...
    'T_s1', 'T_s2', 'T_s3', 'T_s4', 'optimal_objective_r', ...
    'optimal_objective_s', 'relative_regret_obj_r_to_s', ...
    'relative_regret_obj_s_to_r', 'regret_obj_r_to_s', ...
    'regret_obj_s_to_r', 'regret_loss_r_to_s', ...
    'regret_loss_s_to_r', 'tier_1'};
if ~all(ismember(requiredCross, crossTbl.Properties.VariableNames))
    error('Step-03T Step-03S cross-regret schema mismatch.');
end
if height(crossTbl) ~= 125755 || height(falseTbl) ~= 7743 || ...
        height(neighborTbl) ~= 174157 || height(selectedStates) ~= 6 || ...
        height(stateProfiles) ~= 3990 || numel(acceptance) - 1 ~= 20
    error('Step-03T Step-03S frozen row counts mismatch.');
end
if ~isequal(sort(double(selectedStates.initial_state_id)), ...
        sort(config.states))
    error('Step-03T selected state set differs from Step-03S.');
end
if sum(as_logical(crossTbl.tier_1)) ~= 7733
    error('Step-03T frozen Tier-1 count is not 7733.');
end
if any(~contains(acceptance(2:end), ",PASS,"))
    error('Step-03T Step-03S acceptance input contains failures.');
end
end

function [selected, lines] = select_pairs(crossTbl, config)
tier = crossTbl(as_logical(crossTbl.tier_1), :);
records = cell(0, 1);
for ss = 1:numel(config.states)
    stateId = config.states(ss);
    local = tier(double(tier.initial_state_id) == stateId, :);
    if isempty(local)
        error('Step-03T state %d has no Tier-1 rows.', stateId);
    end
    severity = min(double(local.relative_regret_obj_r_to_s), ...
        double(local.relative_regret_obj_s_to_r));
    chosen = zeros(0, 1);
    [~, orderDistance] = sortrows([double(local.d_new), ...
        double(local.scenario_r), double(local.scenario_s)], [1, 2, 3]);
    chosen(end + 1) = orderDistance(1); %#ok<AGROW>
    [~, orderSeverity] = sortrows([-severity, double(local.d_new), ...
        double(local.scenario_r), double(local.scenario_s)], [1, 2, 3, 4]);
    chosen(end + 1) = first_new(orderSeverity, chosen); %#ok<AGROW>
    categoryPriority = category_priority(string(local.pair_type));
    structural = double(local.A_reachability_change_count) + ...
        double(local.changed_local_count) + ...
        double(local.T_L1_difference_kg) ./ 10;
    [~, orderCategory] = sortrows([categoryPriority, -structural, ...
        double(local.d_new), double(local.scenario_r), ...
        double(local.scenario_s)], [1, 2, 3, 4, 5]);
    while numel(unique(chosen)) < config.maximumTierPairsPerState
        chosen(end + 1) = first_new(orderCategory, chosen); %#ok<AGROW>
    end
    chosen = unique(chosen, 'stable');
    rules = ["MINIMUM_D_NEW"; "MAXIMUM_BIDIRECTIONAL_SEVERITY"; ...
        "CATEGORY_REPRESENTATIVE"];
    for kk = 1:numel(chosen)
        records{end + 1, 1} = selected_record(local(chosen(kk), :), ...
            "TIER1", rules(kk), severity(chosen(kk))); %#ok<AGROW>
    end

    controls = crossTbl(double(crossTbl.initial_state_id) == stateId & ...
        double(crossTbl.nearest_all_rank) <= 10 & ...
        double(crossTbl.d_new) > config.zeroDistanceTolerance & ...
        double(crossTbl.relative_regret_obj_r_to_s) < ...
            config.lowRegretThreshold & ...
        double(crossTbl.relative_regret_obj_s_to_r) < ...
            config.lowRegretThreshold, :);
    if isempty(controls)
        error('Step-03T state %d has no nonzero low-regret control.', stateId);
    end
    targetDistance = median(double(local(chosen, :).d_new));
    score = abs(log(max(double(controls.d_new), eps) ./ ...
        max(targetDistance, eps)));
    [~, controlOrder] = sortrows([score, double(controls.d_new), ...
        double(controls.scenario_r), double(controls.scenario_s)], ...
        [1, 2, 3, 4]);
    controlSeverity = min(double(controls.relative_regret_obj_r_to_s), ...
        double(controls.relative_regret_obj_s_to_r));
    records{end + 1, 1} = selected_record(controls(controlOrder(1), :), ...
        "CONTROL", "LOW_REGRET_DISTANCE_MATCHED", ...
        controlSeverity(controlOrder(1))); %#ok<AGROW>
end
selected = records_to_table(records);
selected.pair_id = (1:height(selected)).';
selected = movevars(selected, 'pair_id', 'Before', 1);
if height(selected) > config.maximumPairCount
    error('Step-03T selected more than 24 pairs.');
end
lines = ["# Step-03T Pair Selection Rationale"; ""; ...
    "Selection is deterministic and reads only the frozen Step-03S cross-regret table."; ...
    "Each of states 7, 18, 30, 31, 11, and 21 contributes three distinct Tier-1 representatives and one nonzero-distance low-regret control."; ...
    "Tier-1 rules are minimum d_new, maximum min(two directional objective regrets), and a category/structural representative preferring tail-tail then non-tail/tail."; ...
    "Controls are nearest-all pairs with both directional relative objective regrets below 1%, selected closest on a log-distance scale to the state's Tier-1 median distance."; ...
    "No nearest-neighbor search, scenario optimization, or Step-03S calculation is repeated during selection."; ""];
for rr = 1:height(selected)
    lines(end + 1) = "- pair " + selected.pair_id(rr) + ...
        ": state " + selected.initial_state_id(rr) + ", " + ...
        selected.group_type(rr) + ", rule=" + selected.selection_rule(rr) + ...
        ", scenarios " + selected.scenario_r(rr) + "-" + ...
        selected.scenario_s(rr) + ", d_new=" + ...
        sprintf('%.12g', selected.d_new(rr)) + ", severity=" + ...
        sprintf('%.12g', selected.bidirectional_severity(rr)) + "."; %#ok<AGROW>
end
end

function idx = first_new(order, chosen)
for ii = 1:numel(order)
    if ~ismember(order(ii), chosen)
        idx = order(ii);
        return;
    end
end
error('Step-03T could not find a distinct representative pair.');
end

function priority = category_priority(labels)
priority = 3 * ones(numel(labels), 1);
priority(labels == "TAIL_TAIL") = 1;
priority(labels == "NONTAIL_TAIL") = 2;
end

function rec = selected_record(row, groupType, rule, severity)
rec = table2struct(row);
rec.group_type = groupType;
rec.selection_rule = rule;
rec.bidirectional_severity = severity;
rec.relative_regret_loss_r_to_s = double(row.regret_loss_r_to_s) / ...
    max(abs(double(row.own_operating_loss_s)), 1e-8);
rec.relative_regret_loss_s_to_r = double(row.regret_loss_s_to_r) / ...
    max(abs(double(row.own_operating_loss_r)), 1e-8);
rec.relative_regret_loss_source = ...
    "derived_from_frozen_absolute_regret_and_own_operating_loss";
end

function [pairData, audit] = load_selected_pair_data(selected, matPath, ...
        checkpointDir, nodeX, nodeY, config)
m = matfile(matPath);
P = height(selected);
pairData = repmat(struct('D_r', [], 'A_r', [], 'C_r', [], ...
    'D_s', [], 'A_s', [], 'C_s', [], 'Dscale', NaN, ...
    'path_r', NaN, 'path_s', NaN, 'centroid_r', [], 'centroid_s', []), P, 1);
distanceError = zeros(P, 3);
checkpointError = zeros(P, 1);
checkpointRelativeError = zeros(P, 1);
identityPass = true(P, 1);
loadedCross = cell(numel(config.states), 1);
loadedScale = NaN(numel(config.states), 1);
for ss = 1:numel(config.states)
    stateId = config.states(ss);
    depth = load(fullfile(checkpointDir, ...
        sprintf('depth_state_%02d.mat', stateId)), 'stateDepth');
    scale = load(fullfile(checkpointDir, ...
        sprintf('neighbors_state_%02d.mat', stateId)), 'Dscale');
    loadedCross{ss} = depth.stateDepth.cross;
    loadedScale(ss) = scale.Dscale;
end
critical = {'d_D', 'd_Ctilde', 'd_new', 'T_r1', 'T_r2', 'T_r3', ...
    'T_r4', 'T_s1', 'T_s2', 'T_s3', 'T_s4', ...
    'optimal_objective_r', 'optimal_objective_s', ...
    'regret_loss_r_to_s', 'regret_loss_s_to_r'};
relativeFields = {'relative_regret_obj_r_to_s', ...
    'relative_regret_obj_s_to_r'};
for pp = 1:P
    stateId = double(selected.initial_state_id(pp));
    statePos = find(config.states == stateId, 1);
    r = double(selected.scenario_r(pp));
    s = double(selected.scenario_s(pp));
    globalR = (stateId - 1) * config.rowsPerState + r;
    globalS = (stateId - 1) * config.rowsPerState + s;
    pairData(pp).D_r = double(m.D_node_kg(globalR, :));
    pairData(pp).A_r = logical(m.A_site_node(globalR, :, :));
    pairData(pp).C_r = double(m.C_site_node_km(globalR, :, :));
    pairData(pp).D_s = double(m.D_node_kg(globalS, :));
    pairData(pp).A_s = logical(m.A_site_node(globalS, :, :));
    pairData(pp).C_s = double(m.C_site_node_km(globalS, :, :));
    pairData(pp).path_r = double(m.path_id(globalR, 1));
    pairData(pp).path_s = double(m.path_id(globalS, 1));
    pairData(pp).Dscale = loadedScale(statePos);
    pairData(pp).centroid_r = demand_centroid(pairData(pp).D_r, nodeX, nodeY);
    pairData(pp).centroid_s = demand_centroid(pairData(pp).D_s, nodeX, nodeY);
    [dNew, dD, dC] = step03S_distance_block_h2( ...
        pairData(pp).D_r, pairData(pp).A_r, pairData(pp).C_r, ...
        pairData(pp).D_s, pairData(pp).A_s, pairData(pp).C_s, ...
        pairData(pp).Dscale, config);
    distanceError(pp, :) = abs([dD - double(selected.d_D(pp)), ...
        dC - double(selected.d_Ctilde(pp)), ...
        dNew - double(selected.d_new(pp))]);
    cp = loadedCross{statePos};
    hit = cp(double(cp.scenario_r) == r & double(cp.scenario_s) == s, :);
    if height(hit) ~= 1
        identityPass(pp) = false;
        checkpointError(pp) = Inf;
    else
        errs = zeros(numel(critical), 1);
        for kk = 1:numel(critical)
            errs(kk) = abs(double(hit.(critical{kk})(1)) - ...
                double(selected.(critical{kk})(pp)));
        end
        checkpointError(pp) = max(errs);
        relativeErrs = zeros(numel(relativeFields), 1);
        for kk = 1:numel(relativeFields)
            lhs = double(hit.(relativeFields{kk})(1));
            rhs = double(selected.(relativeFields{kk})(pp));
            relativeErrs(kk) = abs(lhs - rhs) / max([1, abs(lhs), abs(rhs)]);
        end
        checkpointRelativeError(pp) = max(relativeErrs);
        identityPass(pp) = pairData(pp).path_r == ...
            double(selected.path_id_r(pp)) && pairData(pp).path_s == ...
            double(selected.path_id_s(pp));
    end
end
audit = struct('max_distance_error', max(distanceError, [], 'all'), ...
    'max_checkpoint_error', max(checkpointError), ...
    'max_checkpoint_relative_regret_normalized_error', ...
        max(checkpointRelativeError), ...
    'identity_pass', all(identityPass), ...
    'distance_error', distanceError, ...
    'checkpoint_error', checkpointError);
end

function centroid = demand_centroid(D, nodeX, nodeY)
total = sum(D);
if total <= 1e-12
    centroid = [NaN, NaN];
else
    centroid = [sum(D .* nodeX) / total, sum(D .* nodeY) / total];
end
end

function [jointTbl, demandTbl, serviceTbl, ctildeTbl, diagnostic] = ...
        diagnose_pairs(selected, pairData, nodeX, nodeY, Cap, config)
P = height(selected);
jointRecords = cell(P, 1);
demandRecords = cell(0, 1);
serviceRecords = cell(0, 1);
ctildeRecords = cell(0, 1);
diagnostic = cell(P, 1);
for pp = 1:P
    r = scenario_features(pairData(pp).D_r, pairData(pp).A_r, ...
        pairData(pp).C_r, nodeX, nodeY);
    s = scenario_features(pairData(pp).D_s, pairData(pp).A_s, ...
        pairData(pp).C_s, nodeX, nodeY);
    Ddiff = abs(pairData(pp).D_r - pairData(pp).D_s);
    [~, dOrder] = sortrows([-Ddiff(:), (1:33).'], [1, 2]);
    topD = dOrder(1:5);
    for kk = 1:5
        nn = topD(kk);
        denom = max([abs(pairData(pp).D_r(nn)), ...
            abs(pairData(pp).D_s(nn)), 1e-12]);
        demandRecords{end + 1, 1} = struct('pair_id', pp, ...
            'group_type', selected.group_type(pp), ...
            'initial_state_id', selected.initial_state_id(pp), ...
            'rank', kk, 'node_id', nn, 'node_x_km', nodeX(nn), ...
            'node_y_km', nodeY(nn), 'D_r_kg', pairData(pp).D_r(nn), ...
            'D_s_kg', pairData(pp).D_s(nn), ...
            'absolute_difference_kg', Ddiff(nn), ...
            'relative_difference', Ddiff(nn) / denom); %#ok<AGROW>
    end

    serviceChanged = r.service_count ~= s.service_count | ...
        r.best_site ~= s.best_site | r.reachable_mask ~= s.reachable_mask;
    for nn = 1:33
        serviceRecords{end + 1, 1} = struct('pair_id', pp, ...
            'group_type', selected.group_type(pp), ...
            'initial_state_id', selected.initial_state_id(pp), ...
            'node_id', nn, 'D_r_kg', pairData(pp).D_r(nn), ...
            'D_s_kg', pairData(pp).D_s(nn), ...
            'service_set_r', service_set_string(r.A(:, nn)), ...
            'service_set_s', service_set_string(s.A(:, nn)), ...
            'service_count_r', r.service_count(nn), ...
            'service_count_s', s.service_count(nn), ...
            'best_site_r', r.best_site(nn), 'best_site_s', s.best_site(nn), ...
            'second_site_r', r.second_site(nn), ...
            'second_site_s', s.second_site(nn), ...
            'best_cost_r_km', r.best_cost(nn), ...
            'best_cost_s_km', s.best_cost(nn), ...
            'second_best_gap_r_km', r.second_gap(nn), ...
            'second_best_gap_s_km', s.second_gap(nn), ...
            'service_relation_changed', serviceChanged(nn), ...
            'unreachable_to_reachable', r.service_count(nn) == 0 && ...
                s.service_count(nn) > 0, ...
            'reachable_to_unreachable', r.service_count(nn) > 0 && ...
                s.service_count(nn) == 0, ...
            'multi_to_exclusive', r.service_count(nn) >= 2 && ...
                s.service_count(nn) == 1, ...
            'exclusive_to_multi', r.service_count(nn) == 1 && ...
                s.service_count(nn) >= 2, ...
            'exclusive_site_swap', r.service_count(nn) == 1 && ...
                s.service_count(nn) == 1 && r.best_site(nn) ~= s.best_site(nn)); %#ok<AGROW>
    end

    local = local_ctilde(pairData(pp).A_r, pairData(pp).C_r, ...
        pairData(pp).A_s, pairData(pp).C_s, config);
    [~, cOrder] = sortrows([-local(:), (1:132).'], [1, 2]);
    for kk = 1:10
        flat = cOrder(kk);
        [ii, nn] = ind2sub([4, 33], flat);
        ctildeRecords{end + 1, 1} = struct('pair_id', pp, ...
            'group_type', selected.group_type(pp), ...
            'initial_state_id', selected.initial_state_id(pp), ...
            'rank', kk, 'site_id', ii, 'node_id', nn, ...
            'local_Ctilde_difference', local(ii, nn), ...
            'A_r', r.A(ii, nn), 'A_s', s.A(ii, nn), ...
            'C_r_km', finite_or_nan(r.C(ii, nn), r.A(ii, nn)), ...
            'C_s_km', finite_or_nan(s.C(ii, nn), s.A(ii, nn)), ...
            'D_r_kg', pairData(pp).D_r(nn), ...
            'D_s_kg', pairData(pp).D_s(nn)); %#ok<AGROW>
    end

    aChanged = r.A ~= s.A;
    changedNodes = any(aChanged, 1);
    affectedDemand = sum(max(pairData(pp).D_r, pairData(pp).D_s) .* changedNodes);
    bestChanged = r.best_site ~= s.best_site & ...
        r.best_site > 0 & s.best_site > 0;
    bestChangedDemand = sum(max(pairData(pp).D_r, pairData(pp).D_s) .* bestChanged);
    countChangedDemand = sum(max(pairData(pp).D_r, pairData(pp).D_s) .* ...
        (r.service_count ~= s.service_count));
    totalMean = max(mean([r.total_D, s.total_D]), 1e-12);
    relocationShare = max(sum(Ddiff) - abs(r.total_D - s.total_D), 0) / ...
        max(sum(Ddiff), 1e-12);
    jointRecords{pp} = joint_record(selected(pp, :), r, s, ...
        affectedDemand, bestChangedDemand, countChangedDemand, ...
        relocationShare, pairData(pp), Cap);
    diagnostic{pp} = struct('r', r, 's', s, ...
        'total_mean', totalMean, 'D_l1', sum(Ddiff), ...
        'total_D_difference', abs(r.total_D - s.total_D), ...
        'relocation_share', relocationShare, ...
        'A_change_count', sum(aChanged, 'all'), ...
        'affected_demand', affectedDemand, ...
        'affected_demand_ratio', affectedDemand / totalMean, ...
        'service_count_change_nodes', sum(r.service_count ~= s.service_count), ...
        'service_count_changed_demand', countChangedDemand, ...
        'best_site_change_nodes', sum(bestChanged), ...
        'best_site_changed_demand', bestChangedDemand, ...
        'exclusive_change', sum(abs(r.exclusive_D - s.exclusive_D)), ...
        'shared_change', abs(r.shared_D - s.shared_D), ...
        'unreachable_change', abs(r.unreachable_D - s.unreachable_D), ...
        'coverage_change', sum(abs(r.covered_D - s.covered_D)), ...
        'ranking_change_nodes', sum(r.ranking_code ~= s.ranking_code), ...
        'best_cost_change', nan_sum(abs(r.best_cost - s.best_cost)), ...
        'second_gap_change', nan_sum(abs(r.second_gap - s.second_gap)), ...
        'top_D_nodes', topD(:).', 'top_C_relations', cOrder(1:10).');
end
jointTbl = records_to_table(jointRecords);
demandTbl = records_to_table(demandRecords);
serviceTbl = records_to_table(serviceRecords);
ctildeTbl = records_to_table(ctildeRecords);
diagnostic = vertcat(diagnostic{:});
end

function f = scenario_features(D, A3, C3, nodeX, nodeY)
A = reshape(logical(A3), 4, 33);
C = reshape(double(C3), 4, 33);
serviceCount = sum(A, 1);
covered = sum(A .* D, 2).';
exclusive = zeros(1, 4);
for ii = 1:4
    exclusive(ii) = sum(D .* (A(ii, :) & serviceCount == 1));
end
unreachable = sum(D(serviceCount == 0));
shared = sum(D(serviceCount >= 2));
bestCost = NaN(1, 33);
secondCost = NaN(1, 33);
bestSite = zeros(1, 33);
secondSite = zeros(1, 33);
rankingCode = strings(1, 33);
bestAssigned = zeros(1, 4);
weightedBurden = zeros(1, 4);
for ii = 1:4
    vals = C(ii, :);
    vals(~A(ii, :) | ~isfinite(vals)) = 0;
    weightedBurden(ii) = sum(D .* vals);
end
for nn = 1:33
    sites = find(A(:, nn));
    if isempty(sites)
        rankingCode(nn) = "NONE";
        continue;
    end
    [costs, ord] = sort(C(sites, nn), 'ascend');
    sites = sites(ord);
    bestCost(nn) = costs(1);
    bestSite(nn) = sites(1);
    bestAssigned(sites(1)) = bestAssigned(sites(1)) + D(nn);
    if numel(sites) >= 2
        secondCost(nn) = costs(2);
        secondSite(nn) = sites(2);
    end
    rankingCode(nn) = join(string(sites), ">");
end
secondGap = secondCost - bestCost;
centroid = demand_centroid(D, nodeX, nodeY);
f = struct('D', D, 'A', A, 'C', C, 'total_D', sum(D), ...
    'covered_D', covered, 'exclusive_D', exclusive, ...
    'unreachable_D', unreachable, 'shared_D', shared, ...
    'service_count', serviceCount, 'reachable_mask', serviceCount > 0, ...
    'best_cost', bestCost, 'second_cost', secondCost, ...
    'second_gap', secondGap, 'best_site', bestSite, ...
    'second_site', secondSite, 'ranking_code', rankingCode, ...
    'best_assigned_D', bestAssigned, ...
    'weighted_service_burden', weightedBurden, 'centroid', centroid);
end

