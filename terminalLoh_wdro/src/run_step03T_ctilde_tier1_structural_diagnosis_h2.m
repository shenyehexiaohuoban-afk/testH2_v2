function value = percentile(x, probability)
x = sort(double(x(:)));
if isempty(x)
    value = NaN;
    return;
end
position = 1 + (numel(x) - 1) * probability;
lo = floor(position);
hi = ceil(position);
if lo == hi
    value = x(lo);
else
    value = x(lo) + (position - lo) * (x(hi) - x(lo));
end
end

function tf = as_logical(value)
if islogical(value)
    tf = value;
elseif isnumeric(value)
    tf = value ~= 0;
else
    tf = lower(string(value)) == "true" | string(value) == "1";
end
end

function tbl = records_to_table(records)
