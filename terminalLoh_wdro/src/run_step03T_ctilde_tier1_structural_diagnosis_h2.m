end

function [tbl, out] = tier1_concentration(crossTbl, config)
tier = crossTbl(as_logical(crossTbl.tier_1), :);
state = double(tier.initial_state_id);
r = double(tier.scenario_r);
s = double(tier.scenario_s);
lo = min(r, s);
hi = max(r, s);
unorderedKey = string(state) + ":" + string(lo) + ":" + string(hi);
orientedKey = string(state) + ":" + string(r) + ":" + string(s);
[uniqueUnordered, ~, unorderedGroup] = unique(unorderedKey);
[~, ~, orientedGroup] = unique(orientedKey);
unorderedCounts = accumarray(unorderedGroup, 1);
orientedCounts = accumarray(orientedGroup, 1);
reverseDuplicateClasses = sum(unorderedCounts > 1);
reverseDuplicateRows = sum(unorderedCounts(unorderedCounts > 1));
exactDuplicateRows = sum(orientedCounts - 1);
scenarioKeyR = string(state) + ":" + string(r);
scenarioKeyS = string(state) + ":" + string(s);
allScenarioKeys = [scenarioKeyR; scenarioKeyS];
[uniqueScenarios, ~, scenarioGroup] = unique(allScenarioKeys);
degree = accumarray(scenarioGroup, 1);
[degreeSorted, degreeOrder] = sort(degree, 'descend');
topScenarios = uniqueScenarios(degreeOrder);

topCount = min(20, numel(topScenarios));
records = cell(6 + 2 * numel(config.states) + topCount + 11, 1);
recPos = 0;
recPos = recPos + 1;
records{recPos} = concentration_record("ALL", ...
    "tier1_raw_row_count", NaN, NaN, NaN, height(tier), height(tier), 1);
recPos = recPos + 1;
records{recPos} = concentration_record("ALL", ...
    "unordered_unique_pair_count", NaN, NaN, NaN, ...
    numel(uniqueUnordered), height(tier), numel(uniqueUnordered) / height(tier));
recPos = recPos + 1;
records{recPos} = concentration_record("ALL", ...
    "reverse_duplicate_unordered_classes", NaN, NaN, NaN, ...
    reverseDuplicateClasses, numel(uniqueUnordered), ...
    reverseDuplicateClasses / max(numel(uniqueUnordered), 1));
recPos = recPos + 1;
records{recPos} = concentration_record("ALL", ...
    "rows_in_reverse_duplicate_classes", NaN, NaN, NaN, ...
    reverseDuplicateRows, height(tier), reverseDuplicateRows / height(tier));
recPos = recPos + 1;
records{recPos} = concentration_record("ALL", ...
    "exact_oriented_duplicate_rows", NaN, NaN, NaN, exactDuplicateRows, ...
    height(tier), exactDuplicateRows / height(tier));
recPos = recPos + 1;
records{recPos} = concentration_record("ALL", ...
    "unique_scenario_count", NaN, NaN, NaN, numel(uniqueScenarios), ...
    2 * height(tier), numel(uniqueScenarios) / (2 * height(tier)));
for ss = 1:numel(config.states)
    stateId = config.states(ss);
    mask = state == stateId;
    keys = unique([scenarioKeyR(mask); scenarioKeyS(mask)]);
    recPos = recPos + 1;
    records{recPos} = concentration_record("STATE", ...
        "tier1_pair_count", NaN, stateId, NaN, sum(mask), height(tier), ...
        sum(mask) / height(tier));
    recPos = recPos + 1;
    records{recPos} = concentration_record("STATE", ...
        "unique_scenario_count", NaN, stateId, NaN, numel(keys), ...
        numel(uniqueScenarios), numel(keys) / numel(uniqueScenarios));
end
for kk = 1:topCount
    parts = split(topScenarios(kk), ":");
    recPos = recPos + 1;
    records{recPos} = concentration_record("TOP_SCENARIO", ...
        "incident_pair_count", kk, str2double(parts(1)), ...
        str2double(parts(2)), degreeSorted(kk), height(tier), ...
        degreeSorted(kk) / height(tier));
end
fractions = [0.01, 0.05, 0.10];
remainingShares = zeros(size(fractions));
remainingStates = zeros(size(fractions));
incidentShares = zeros(size(fractions));
for ff = 1:numel(fractions)
    count = max(1, ceil(fractions(ff) * numel(uniqueScenarios)));
    high = topScenarios(1:count);
    incident = ismember(scenarioKeyR, high) | ismember(scenarioKeyS, high);
    incidentShares(ff) = mean(incident);
    remainingShares(ff) = mean(~incident);
    remainingStates(ff) = numel(unique(state(~incident)));
    recPos = recPos + 1;
    records{recPos} = concentration_record("HIGH_FREQUENCY", ...
        "incident_pair_share", 100 * fractions(ff), NaN, NaN, ...
        sum(incident), height(tier), mean(incident));
    recPos = recPos + 1;
    records{recPos} = concentration_record("HIGH_FREQUENCY", ...
        "remaining_pair_share_after_removal", 100 * fractions(ff), ...
        NaN, NaN, sum(~incident), height(tier), mean(~incident));
    recPos = recPos + 1;
    records{recPos} = concentration_record("HIGH_FREQUENCY", ...
        "remaining_state_count_after_removal", 100 * fractions(ff), ...
        NaN, NaN, remainingStates(ff), numel(config.states), ...
        remainingStates(ff) / numel(config.states));
end
pairType = string(tier.pair_type);
recPos = recPos + 1;
records{recPos} = concentration_record("CATEGORY", ...
    "NONTAIL_TAIL", NaN, NaN, NaN, sum(pairType == "NONTAIL_TAIL"), ...
    height(tier), mean(pairType == "NONTAIL_TAIL"));
recPos = recPos + 1;
records{recPos} = concentration_record("CATEGORY", ...
    "TAIL_TAIL", NaN, NaN, NaN, sum(pairType == "TAIL_TAIL"), ...
    height(tier), mean(pairType == "TAIL_TAIL"));
tbl = records_to_table(records(1:recPos));
out = struct('raw_pair_count', height(tier), ...
    'unordered_unique_pair_count', numel(uniqueUnordered), ...
    'reverse_duplicate_classes', reverseDuplicateClasses, ...
    'reverse_duplicate_rows', reverseDuplicateRows, ...
    'exact_oriented_duplicate_rows', exactDuplicateRows, ...
    'unique_scenario_count', numel(uniqueScenarios), ...
    'top20_scenarios', topScenarios(1:min(20, numel(topScenarios))), ...
    'top20_degrees', degreeSorted(1:min(20, numel(degreeSorted))), ...
    'incident_shares', incidentShares, ...
    'remaining_shares', remainingShares, ...
    'remaining_states', remainingStates, ...
    'non_tail_tail_count', sum(pairType == "NONTAIL_TAIL"), ...
    'tail_tail_count', sum(pairType == "TAIL_TAIL"));
end

