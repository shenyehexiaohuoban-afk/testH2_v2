function [replayTbl, nodeTbl, audit, detail] = replay_selected_pairs( ...
        selected, pairData, M, config)
P = height(selected);
R = 4 * P;
D = zeros(R, 33);
A = false(R, 4, 33);
C = NaN(R, 4, 33);
T = zeros(R, 4);
pairIndex = zeros(R, 1);
labels = strings(R, 1);
targetSide = strings(R, 1);
sourceSide = strings(R, 1);
for pp = 1:P
    rows = (pp - 1) * 4 + (1:4);
    Tr = double([selected.T_r1(pp), selected.T_r2(pp), ...
        selected.T_r3(pp), selected.T_r4(pp)]);
    Ts = double([selected.T_s1(pp), selected.T_s2(pp), ...
        selected.T_s3(pp), selected.T_s4(pp)]);
