            as_logical(selected.capacity_saturated_r(pp)) && ...
            as_logical(selected.capacity_saturated_s(pp)), ...
        'local_average_dilution_supported', ...
            double(selected.local_dilution_ratio(pp)) >= 5 && ...
            double(selected.changed_local_count(pp)) <= 10, ...
        'r_to_s_main_regret_nodes', topR, ...
        's_to_r_main_regret_nodes', topS, ...
        'r_to_s_most_changed_service_site', misplacedR, ...
        's_to_r_most_changed_service_site', misplacedS, ...
        'r_to_s_unused_T_by_site_kg', ...
            join(compose('%.9g', replay(pp).unused_cross_r_to_s), ";"), ...
