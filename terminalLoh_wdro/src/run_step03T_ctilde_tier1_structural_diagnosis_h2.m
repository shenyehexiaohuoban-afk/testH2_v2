function local = local_ctilde(Ar3, Cr3, As3, Cs3, config)
Ar = reshape(logical(Ar3), 4, 33);
As = reshape(logical(As3), 4, 33);
Cr = reshape(double(Cr3), 4, 33);
Cs = reshape(double(Cs3), 4, 33);
local = config.kappa .* double(xor(Ar, As));
both = Ar & As;
delta = abs(Cr - Cs) ./ config.C_bound;
delta(~both | ~isfinite(delta)) = 0;
local(both) = delta(both);
end

