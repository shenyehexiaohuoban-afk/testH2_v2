            family = "MIXED";
        end
        if relocation >= 0.60 && ~contains(primary, "TYPE_1")
            secondary = "TYPE_1_SPATIAL_DEMAND_RELOCATION";
        elseif bestSiteRatio >= 0.05 && ~contains(primary, "TYPE_5")
            secondary = "TYPE_5_ROAD_IMPEDANCE_RANKING_CHANGE";
        elseif localDilution && ~contains(primary, "TYPE_7")
