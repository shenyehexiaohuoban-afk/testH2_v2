    A(rows, :, :) = cat(1, pairData(pp).A_r, pairData(pp).A_s, ...
        pairData(pp).A_s, pairData(pp).A_r);
    C(rows, :, :) = cat(1, pairData(pp).C_r, pairData(pp).C_s, ...
        pairData(pp).C_s, pairData(pp).C_r);
    T(rows, :) = [Tr; Ts; Tr; Ts];
    pairIndex(rows) = pp;
    labels(rows) = ["T_R_ON_R"; "T_S_ON_S"; "T_R_ON_S"; "T_S_ON_R"];
    targetSide(rows) = ["R"; "S"; "S"; "R"];
    sourceSide(rows) = ["R"; "S"; "R"; "S"];
end
ev = evaluate_step03T_fixed_T_recourse_h2(D, A, C, T, M, config);
records = cell(R, 1);
nodeRecords = cell(R * 33, 1);
detail = cell(P, 1);
nodePos = 0;
objectiveError = zeros(P, 4);
regretError = zeros(P, 4);
objectiveWithinTolerance = false(P, 4);
regretWithinTolerance = false(P, 4);
nodeReconstruction = zeros(P, 2);
for rr = 1:R
    pp = pairIndex(rr);
    records{rr} = struct('pair_id', pp, ...
        'group_type', selected.group_type(pp), ...
        'initial_state_id', selected.initial_state_id(pp), ...
        'replay_case', labels(rr), 'T_source_scenario', sourceSide(rr), ...
        'target_scenario', targetSide(rr), 'solver_status', ev.status, ...
        'service_cost', ev.service_cost(rr), ...
        'shortage_kg', ev.shortage_kg(rr), ...
        'shortage_loss', ev.shortage_loss(rr), ...
        'operating_loss', ev.operating_loss(rr), ...
        'holding_cost', ev.holding_cost(rr), ...
        'full_objective', ev.full_objective(rr));
    for ii = 1:4
        records{rr}.(sprintf('T_site%d_kg', ii)) = T(rr, ii);
        records{rr}.(sprintf('service_site%d_kg', ii)) = ev.site_service(rr, ii);
        records{rr}.(sprintf('unused_T_site%d_kg', ii)) = ev.unused_T(rr, ii);
        records{rr}.(sprintf('transport_site%d', ii)) = ...
            ev.transport_by_site(rr, ii);
    end
    if labels(rr) == "T_R_ON_S"
        baseline = (pp - 1) * 4 + 2;
        direction = "R_TO_S";
    elseif labels(rr) == "T_S_ON_R"
        baseline = (pp - 1) * 4 + 1;
        direction = "S_TO_R";
    else
        baseline = rr;
        direction = "OWN";
    end
    contribution = ev.node_operating_loss(rr, :) - ...
        ev.node_operating_loss(baseline, :);
    [~, contributionOrder] = sort(contribution, 'descend');
    rank = zeros(1, 33);
    rank(contributionOrder) = 1:33;
    for nn = 1:33
        nodePos = nodePos + 1;
        nodeRecords{nodePos} = struct('pair_id', pp, ...
            'group_type', selected.group_type(pp), ...
            'initial_state_id', selected.initial_state_id(pp), ...
            'replay_case', labels(rr), 'direction', direction, ...
            'node_id', nn, 'demand_kg', D(rr, nn), ...
            'service_total_kg', ev.node_service(rr, nn), ...
            'shortage_kg', ev.u(rr, nn), ...
            'transport_loss', ev.transport_by_node(rr, nn), ...
            'shortage_loss', ev.shortage_loss_by_node(rr, nn), ...
            'node_operating_loss', ev.node_operating_loss(rr, nn), ...
            'operating_regret_contribution', contribution(nn), ...
            'positive_contribution_rank', rank(nn));
        for ii = 1:4
            nodeRecords{nodePos}.(sprintf('service_from_site%d_kg', ii)) = ...
                ev.y(rr, ii, nn);
            nodeRecords{nodePos}.(sprintf('transport_from_site%d', ii)) = ...
                ev.transport_by_relation(rr, ii, nn);
        end
    end
end
for pp = 1:P
    rows = (pp - 1) * 4 + (1:4);
    Tr = double([selected.T_r1(pp), selected.T_r2(pp), ...
        selected.T_r3(pp), selected.T_r4(pp)]);
    Ts = double([selected.T_s1(pp), selected.T_s2(pp), ...
        selected.T_s3(pp), selected.T_s4(pp)]);
    representativeObjR = double(selected.own_operating_loss_r(pp)) + ...
        config.gamma * sum(Tr);
    representativeObjS = double(selected.own_operating_loss_s(pp)) + ...
        config.gamma * sum(Ts);
    recordedObj = [representativeObjR, representativeObjS, ...
        double(selected.cross_objective_r_to_s(pp)), ...
        double(selected.cross_objective_s_to_r(pp))];
    objectiveError(pp, :) = abs(ev.full_objective(rows).' - recordedObj);
    objectiveTolerance = config.chainTolerance + 4 .* ...
        eps(max(abs(recordedObj), 1));
    objectiveWithinTolerance(pp, :) = ...
        objectiveError(pp, :) <= objectiveTolerance;
    replayRegret = [ev.full_objective(rows(3)) - ...
        representativeObjS, ev.full_objective(rows(4)) - representativeObjR, ...
        ev.operating_loss(rows(3)) - double(selected.own_operating_loss_s(pp)), ...
        ev.operating_loss(rows(4)) - double(selected.own_operating_loss_r(pp))];
    nodeReplayRegret = [ev.operating_loss(rows(3)) - ...
        ev.operating_loss(rows(2)), ev.operating_loss(rows(4)) - ...
        ev.operating_loss(rows(1))];
    recordedRegret = [double(selected.regret_obj_r_to_s(pp)), ...
        double(selected.regret_obj_s_to_r(pp)), ...
        double(selected.regret_loss_r_to_s(pp)), ...
        double(selected.regret_loss_s_to_r(pp))];
    regretError(pp, :) = abs(replayRegret - recordedRegret);
    regretOperandsLeft = [ev.full_objective(rows(3)), ...
        ev.full_objective(rows(4)), ev.operating_loss(rows(3)), ...
        ev.operating_loss(rows(4))];
    regretOperandsRight = [representativeObjS, representativeObjR, ...
        double(selected.own_operating_loss_s(pp)), ...
        double(selected.own_operating_loss_r(pp))];
    regretTolerance = config.chainTolerance + 4 .* ( ...
        eps(max(abs(regretOperandsLeft), 1)) + ...
        eps(max(abs(regretOperandsRight), 1)));
    regretWithinTolerance(pp, :) = regretError(pp, :) <= regretTolerance;
    nodeReconstruction(pp, :) = [abs(sum(ev.node_operating_loss(rows(3), :) - ...
        ev.node_operating_loss(rows(2), :)) - nodeReplayRegret(1)), ...
        abs(sum(ev.node_operating_loss(rows(4), :) - ...
        ev.node_operating_loss(rows(1), :)) - nodeReplayRegret(2))];
    [~, topRtoS] = sort(ev.node_operating_loss(rows(3), :) - ...
        ev.node_operating_loss(rows(2), :), 'descend');
    [~, topStoR] = sort(ev.node_operating_loss(rows(4), :) - ...
        ev.node_operating_loss(rows(1), :), 'descend');
    detail{pp} = struct('rows', rows, ...
        'top_nodes_r_to_s', topRtoS(1:5), ...
        'top_nodes_s_to_r', topStoR(1:5), ...
        'service_delta_r_to_s', ev.site_service(rows(3), :) - ...
            ev.site_service(rows(2), :), ...
        'service_delta_s_to_r', ev.site_service(rows(4), :) - ...
            ev.site_service(rows(1), :), ...
        'unused_cross_r_to_s', ev.unused_T(rows(3), :), ...
        'unused_cross_s_to_r', ev.unused_T(rows(4), :));
end
replayTbl = records_to_table(records);
nodeTbl = records_to_table(nodeRecords);
detail = vertcat(detail{:});
audit = struct('all_optimal', ev.exitflag == 1 && ev.status == "OPTIMAL", ...
    'replay_count', R, 'max_objective_error', max(objectiveError, [], 'all'), ...
    'max_regret_error', max(regretError, [], 'all'), ...
    'all_cross_objectives_within_machine_aware_1e8_tolerance', ...
        all(objectiveWithinTolerance(:, 3:4), 'all'), ...
    'all_regrets_within_1e8_plus_operand_ulp_tolerance', ...
        all(regretWithinTolerance, 'all'), ...
    'max_node_reconstruction_error', max(nodeReconstruction, [], 'all'), ...
    'max_balance_error', ev.max_demand_balance_error, ...
    'max_capacity_violation', ev.max_site_capacity_violation, ...
    'objective_reconstruction_error', ev.objective_reconstruction_abs_error);
end

function tbl = classify_failure_modes(selected, diagnostic, replay, config)
records = cell(height(selected), 1);
for pp = 1:height(selected)
    d = diagnostic(pp);
    if selected.group_type(pp) == "CONTROL"
        primary = "CONTROL_LOW_REGRET";
        secondary = "NONE";
        family = "CONTROL";
    else
        exclusiveRatio = d.exclusive_change / d.total_mean;
        redundancyRatio = d.shared_change / d.total_mean;
        bestSiteRatio = d.best_site_changed_demand / d.total_mean;
        relocation = d.relocation_share;
        localDilution = double(selected.local_dilution_ratio(pp)) >= 5 && ...
            double(selected.changed_local_count(pp)) <= 10;
        bothSaturated = as_logical(selected.capacity_saturated_r(pp)) && ...
            as_logical(selected.capacity_saturated_s(pp));
        if d.affected_demand_ratio >= 0.10 && exclusiveRatio >= 0.10
            primary = "TYPE_3_STATION_IDENTITY_OR_EXCLUSIVE_COVERAGE";
            family = "SERVICE_COUPLING";
        elseif d.affected_demand_ratio >= 0.10 && redundancyRatio >= 0.10
            primary = "TYPE_4_SERVICE_REDUNDANCY_CHANGE";
            family = "SERVICE_COUPLING";
        elseif d.affected_demand_ratio >= 0.05
            primary = "TYPE_2_DEMAND_REACHABILITY_COUPLING";
            family = "SERVICE_COUPLING";
        elseif bestSiteRatio >= 0.05 || d.ranking_change_nodes >= 3
            primary = "TYPE_5_ROAD_IMPEDANCE_RANKING_CHANGE";
            family = "SERVICE_COUPLING";
