function conclusion = choose_conclusion(failureTbl, chainAudit, replayAudit, ...
        concentration, config)
if chainAudit.max_distance_error > config.distanceTolerance || ...
        chainAudit.max_checkpoint_error > config.chainTolerance || ...
        chainAudit.max_checkpoint_relative_regret_normalized_error > ...
            config.chainTolerance || ...
        ~chainAudit.identity_pass || replayAudit.max_regret_error > ...
        config.chainTolerance && ...
        ~replayAudit.all_regrets_within_1e8_plus_operand_ulp_tolerance
    conclusion = "F. STEP03S_RESULT_REQUIRES_CORRECTION";
    return;
end
tier = failureTbl(failureTbl.group_type == "TIER1", :);
families = string(tier.failure_family);
serviceShare = mean(families == "SERVICE_COUPLING");
spatialShare = mean(families == "SPATIAL_DEMAND");
capacityShare = mean(families == "CAPACITY_SWITCH");
scaleShare = mean(families == "AGGREGATION_SCALE");
if serviceShare >= 0.60
    conclusion = "A. SERVICE_COUPLING_OMISSION_DOMINANT";
elseif spatialShare >= 0.60
    conclusion = "B. SPATIAL_DEMAND_RELOCATION_DOMINANT";
elseif capacityShare >= 0.60
    conclusion = "C. CAPACITY_AND_OPTIMIZATION_SWITCHING_DOMINANT";
elseif scaleShare >= 0.60
    conclusion = "D. AGGREGATION_OR_SCALING_DOMINANT";
elseif concentration.remaining_shares(3) >= 0.25 && ...
        concentration.remaining_states(3) >= 4
    conclusion = "E. MULTIPLE_STRUCTURAL_FAILURE_MODES";
else
    conclusion = "G. DIAGNOSIS_INCONCLUSIVE";
end
end

