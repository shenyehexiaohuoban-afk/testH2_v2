            join(compose('%.9g', replay(pp).unused_cross_s_to_r), ";"), ...
        'bidirectional_cause_explanation', ...
            "Cross layouts alter node shortage/service at nodes " + topR + ...
            " (r-to-s) and " + topS + " (s-to-r); the directions are diagnosed separately.");
