mLegacy=update_rhs_h2(mLegacy,pLegacy,k,3,zeros(4,1));

opts.enable_hourly_grid=true; opts.hourly_grid_vmin_pu=0.90; opts.hourly_grid_vmax_pu=1.10;
pGrid=load_data_h2_near(fullfile(rootDir,'data'),opts.nearInputFile,opts);
mGrid=build_stage_model_h2(pGrid,3);
mGrid=update_rhs_h2(mGrid,pGrid,k,3,zeros(4,1));

legacy=[mLegacy.nvars,size(mLegacy.Aeq,1),size(mLegacy.A,1), ...
    size(mLegacy.Aeq,1)+size(mLegacy.A,1),nnz(mLegacy.Aeq),nnz(mLegacy.A), ...
    nnz(mLegacy.Aeq)+nnz(mLegacy.A)];
grid=[mGrid.nvars,size(mGrid.Aeq,1),size(mGrid.A,1), ...
    size(mGrid.Aeq,1)+size(mGrid.A,1),nnz(mGrid.Aeq),nnz(mGrid.A), ...
    nnz(mGrid.Aeq)+nnz(mGrid.A)];

model=["legacy_total";"hourly_grid_total";"ratio_hourly_over_legacy"; ...
    "hourly_branch_P_variables";"hourly_branch_Q_variables"; ...
    "hourly_voltage_variables";"hourly_PV_variables"; ...
    "hourly_PEL_variables";"hourly_grid_import_variables"; ...
    "hourly_H2_legacy_variables";"constraint_H2_inventory_eq"; ...
    "constraint_H2_production_eq";"constraint_hourly_PEL_link_eq"; ...
    "constraint_grid_P_balance_eq";"constraint_grid_Q_balance_eq"; ...
    "constraint_voltage_drop_eq";"constraint_slack_voltage_eq"; ...
    "constraint_ordinary_demand_ineq";"constraint_HTT_capacity_ineq"; ...
    "constraint_branch_octagon_ineq";"constraint_voltage_bounds"; ...
    "constraint_PV_bounds";"constraint_PEL_bounds"];
variables=[legacy(1);grid(1);grid(1)/legacy(1);numel(mGrid.idx.p_branch); ...
    numel(mGrid.idx.q_branch);numel(mGrid.idx.v_sq);numel(mGrid.idx.p_pv); ...
