opts.terminal_loh_lookup_file=fullfile(rootDir,'results','task-002-stage2b-b3-smoke', ...
    '53-35state-saa-vs-eta003-terminal-loh','run-024','terminal_loh_table_saa.csv');

opts.enable_hourly_grid=false;
pLegacy=load_data_h2_near(fullfile(rootDir,'data'),opts.nearInputFile,opts);
