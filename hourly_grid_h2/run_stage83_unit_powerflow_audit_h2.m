function [duplicateCount,groups] = duplicate_rows(A,b,sense)
keys=cell(size(A,1),1);
for r=1:size(A,1)
    [~,cols,vals]=find(A(r,:));
    if isempty(vals)
        scale=1;
    else
        scale=max(abs(vals));
    end
    vals=vals/scale; rhs=b(r)/scale;
    if sense=="=" && ~isempty(vals) && vals(1)<0
        vals=-vals; rhs=-rhs;
    end
    keys{r}=sprintf('%s|%s|%.15g',sense,sprintf('%d:%.15g;', [cols(:),vals(:)].'),rhs);
end
[u,~,ic]=unique(keys); counts=accumarray(ic,1);
groups=u(counts>1); duplicateCount=sum(counts(counts>1)-1);
end

